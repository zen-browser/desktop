import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { cssValue, loadZenTokens } from "../src/zen/tokens/tokens.mjs";
import {
  STUDIO_FILE,
  buildStudioFile,
  importStudioTokens,
} from "./tokens_studio.mjs";

const OUTPUT = join(
  import.meta.dirname,
  "../src/zen/common/styles/zen-tokens.css"
);

const HEADER = `/*
 * This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at http://mozilla.org/MPL/2.0/.
 */

/* DO NOT EDIT this file directly, instead modify the relevant
 * src/zen/tokens/*.tokens.json file and run \`npm run tokens\`. */
`;

function build() {
  const sections = new Map();
  for (const token of loadZenTokens()) {
    if (token.external) {
      continue;
    }
    const title = `${token.file.replace(/\.tokens\.json$/, "")}: ${token.group}`;
    if (!sections.has(title)) {
      sections.set(title, []);
    }
    sections.get(title).push(`  ${token.name}: ${cssValue(token)};`);
  }
  const body = [...sections]
    .map(([title, lines]) => `  /** ${title} **/\n${lines.join("\n")}`)
    .join("\n\n");
  return `${HEADER}
:host(:is(.anonymous-content-host, notification-message)),
:root {
${body}
}
`;
}

function read(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return "";
  }
}

const fromStudio = process.argv.indexOf("--from-studio");
if (fromStudio !== -1) {
  const source = process.argv[fromStudio + 1];
  const { changed, added, missing, ignored } = importStudioTokens(
    source && !source.startsWith("--") ? source : undefined
  );
  const list = names => names.map(name => `  ${name}`).join("\n");
  if (!changed.length && !added.length) {
    console.log("No tokens changed in Tokens Studio.");
  }
  if (changed.length) {
    console.log(`Updated ${changed.length} token(s):\n${list(changed)}`);
  }
  if (added.length) {
    console.log(`\nAdded ${added.length} new token(s):\n${list(added)}`);
  }
  if (ignored.length) {
    console.log(
      `\nIgnored ${ignored.length} token(s) from Tokens Studio:\n` +
        list(ignored.map(({ name, reason }) => `${name}: ${reason}`))
    );
  }
  if (missing.length) {
    console.log(
      `\n${missing.length} token(s) are in code but not in Tokens Studio. ` +
        `Create them there, or import src/zen/tokens/tokens-studio.json:\n${list(missing)}`
    );
  }
}

const outputs = [
  [OUTPUT, build()],
  [STUDIO_FILE, buildStudioFile()],
];
if (process.argv.includes("--check")) {
  const stale = outputs.filter(([path, text]) => read(path) !== text);
  if (stale.length) {
    console.error(
      `Out of date: ${stale.map(([path]) => path).join(", ")}\n` +
        "Run `npm run tokens` and commit the result."
    );
    process.exit(1);
  }
} else {
  for (const [path, text] of outputs) {
    writeFileSync(path, text);
  }
}
