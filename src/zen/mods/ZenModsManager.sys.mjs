/**
 * Builds the id of the element and the prefix that mods use to select their
 * preferences. Do not change to "mod-": published mods depend on "theme-".
 *
 * @param {string} name - The mod's name
 * @returns {string}
 */
function sanitizeModName(name) {
  return `theme-${String(name ?? "")
    .replaceAll(WHITESPACE_RE, "-")
    .replaceAll(NON_NAME_RE, "")}`;
}

/**
 * @param {object} mod - A validated store entry
 * @returns {object} What the registry keeps of it
 */
function storeEntry(mod) {
  const entry = { ...mod };

  for (const key of MANAGER_FIELDS) {
    delete entry[key];
  }

  return entry;
}

/**
 * @param {*} error
 * @returns {boolean} Whether IOUtils failed because the file is not there
 */
function isNotFound(error) {
  return DOMException.isInstance(error) && error.name === "NotFoundError";
}

/**
 * Lists the files in a mod's folder, the hidden ones and `node_modules`
 * aside, sorted by path.
 *
 * @param {string} folder
 * @param {RegExp|null} match - Only the files whose name matches
 * @param {number} limit - More files than this is an error
 * @returns {Promise<{path: string, info: object}[]>} Each file and its
 * `IOUtils.stat`
 */
async function listModFiles(folder, match, limit) {
  const files = [];
  const visit = async directory => {
    for (const child of await IOUtils.getChildren(directory)) {
      const name = PathUtils.filename(child);

      if (name.startsWith(".") || name === "node_modules") {
        continue;
      }

      const info = await IOUtils.stat(child);

      if (info.type === "directory") {
        await visit(child);
      } else if (!match || match.test(name)) {
        files.push({ path: child, info });
      }

      if (files.length > limit) {
        throw new Error(`[ZenMods]: More than ${limit} files in ${folder}.`);
      }
    }
  };

  await visit(folder);

  return files.sort((first, second) =>
    first.path < second.path ? -1 : Number(first.path > second.path)
  );
}

/**
 * Splits a path from `theme.json` into the folders and file it goes through,
 * as long as it stays inside the mod's folder.
 *
 * @param {*} path - A path like "src/main.mjs"
 * @returns {string[]|null} Its parts, or null if it's not a valid path
 */
function pathParts(path) {
  if (typeof path !== "string" || !path) {
    return null;
  }

  const parts = path.split("/");
  const isValid = parts.every(
    part => part && part !== "." && part !== ".." && !/[\\:]/.test(part)
  );

  return isValid ? parts : null;
}

/**
 * @param {string} path - A valid relative path
 * @returns {string} The path, each part encoded for a URL
 */
function encodePath(path) {
  return pathParts(path).map(encodeURIComponent).join("/");
}

/**
 * Reads where a mod lives on GitHub from what the user typed.
 *
 * shortcut: in a /tree/ URL the branch is one segment, so branches with "/"
 * in their name read as branch and folder; parse the full ref with the API if
 * people need them.
 *
 * @param {*} input - "owner/repo", "owner/repo/folder" or a github.com URL,
 * with "/tree/<branch>/<folder>" for a branch other than the default one
 * @returns {{repo: string, ref: string|null, folder: string}} The
 * repository as "owner/repo", the branch and the folder of the mod
 */
function parseGitHubSource(input) {
  const text = String(input ?? "")
    .trim()
    .replace(GITHUB_URL_RE, "")
    .replace(TRAILING_SLASHES_RE, "");
  const [owner = "", repoName = "", ...rest] = text.split("/");
  const repo = repoName.replace(DOT_GIT_RE, "");
  const isName = name =>
    GITHUB_NAME_RE.test(name) && name !== "." && name !== "..";

  let ref = null;
  let folder = rest;

  if (rest[0] === "tree" && rest.length > 1) {
    ref = rest[1];
    folder = rest.slice(2);
  }

  const isValid =
    isName(owner) &&
    isName(repo) &&
    (ref === null || isName(ref)) &&
    (!folder.length || pathParts(folder.join("/")));

  if (!isValid) {
    throw new Error(`[ZenMods]: Not a GitHub repository: ${input}`);
  }

  return { repo: `${owner}/${repo}`, ref, folder: folder.join("/") };
}

/**
 * @param {object} mod - A mod of the registry installed from GitHub
 * @returns {{repo: string, ref: string|null, folder: string}}
 */
function gitHubSourceOf(mod) {
  return parseGitHubSource(
    [mod.repo, mod.ref && `tree/${mod.ref}`, mod.folder]
      .filter(Boolean)
      .join("/")
  );
}

/**
 * @param {*} value
 * @returns {string[]|null} The strings in a list, or null if it's no list
 */
function stringList(value) {
  return Array.isArray(value)
    ? value.filter(item => typeof item === "string")
    : null;
}

/**
 * Turns the `scripts` of a `theme.json` into one list. A list of paths is
 * Zen's own format: ES modules that export `init(window)` and
 * `uninit(window)`. A map of paths is the userChrome.js format other mod
 * managers use, where folders nest as keys ending in "/": `.uc.js` and
 * `.uc.mjs` files run in each document their `include` patterns match, and
 * `.sys.mjs` files run once.
 *
 * @param {*} scripts
 * @returns {{path: string, kind: "module"|"uc.js"|"uc.mjs", include?: string[], exclude?: string[], loadOrder?: number}[]}
 */
function normalizeScripts(scripts) {
  if (scripts === undefined || scripts === null) {
    return [];
  }

  if (Array.isArray(scripts)) {
    return scripts.map(path => {
      if (!pathParts(path) || !path.endsWith(".mjs")) {
        throw new Error(`[ZenMods]: Invalid script path: ${path}`);
      }

      return { path, kind: "module" };
    });
  }

  if (typeof scripts !== "object") {
    throw new Error(
      '[ZenMods]: "scripts" in theme.json must be a list or a map.'
    );
  }

  const normalized = [];
  const visit = (entries, prefix) => {
    for (const [key, options] of Object.entries(entries)) {
      const path = `${prefix}${key}`;

      if (key.endsWith("/") && options && typeof options === "object") {
        visit(options, path);
        continue;
      }

      const kind = SCRIPT_KINDS.find(([extension]) =>
        path.endsWith(extension)
      )?.[1];

      if (!kind || !pathParts(path)) {
        console.warn(`[ZenMods]: Unsupported script ${path}, skipping.`);
        continue;
      }

      normalized.push({
        path,
        kind,
        include: stringList(options?.include) ?? ["main"],
        exclude: stringList(options?.exclude) ?? [],
        loadOrder: Number.isInteger(options?.loadOrder)
          ? options.loadOrder
          : DEFAULT_LOAD_ORDER,
      });
    }
  };

  visit(scripts, "");

  return normalized;
}

/**
 * Reads what a `theme.json` declares, in Zen's format or in the one other
 * mod managers use, where `style` is `{chrome, content}` and `scripts` is a
 * map.
 *
 * @param {*} manifest
 * @returns {object}
 */
function parseManifest(manifest) {
  if (!manifest || typeof manifest !== "object" || Array.isArray(manifest)) {
    throw new Error("[ZenMods]: theme.json is not an object.");
  }

  const text = key => (typeof manifest[key] === "string" ? manifest[key] : "");
  const isStyleObject =
    Boolean(manifest.style) && typeof manifest.style === "object";
  const style = isStyleObject ? manifest.style.chrome : manifest.style;
  const contentStyle = isStyleObject ? manifest.style.content : null;

  return {
    name: text("name"),
    version: text("version"),
    author: text("author"),
    description: text("description"),
    homepage: text("homepage"),
    stylePath: pathParts(style) ? style : null,
    contentStylePath: pathParts(contentStyle) ? contentStyle : null,
    preferencesPath: pathParts(manifest.preferences)
      ? manifest.preferences
      : "preferences.json",
    scripts: normalizeScripts(manifest.scripts),
  };
}

/**
 * @param {string|null} declared - The style a `theme.json` names, if any
 * @param {(path: string) => Promise<boolean>} exists
 * @returns {Promise<string|null>} The mod's style file, if it has one
 */
async function findStyle(declared, exists) {
  for (const candidate of declared ? [declared] : STYLE_FILES) {
    if (await exists(candidate)) {
      return candidate;
    }
  }

  return null;
}

/**
 * @param {string[]} patterns - URLs where `*` matches anything, or "main"
 * for the browser window
 * @returns {RegExp|null}
 */
function urlPatterns(patterns) {
  const sources = patterns.map(pattern =>
    (pattern === "main" ? MAIN_WINDOW_URL : pattern)
      .replace(REGEXP_SPECIAL_RE, "\\$&")
      .replaceAll("*", ".*")
  );

  return sources.length ? new RegExp(`^(?:${sources.join("|")})$`) : null;
}

/**
 * @param {object} mod - An entry of the registry
 * @returns {object[]} The scripts the mod may run, as `normalizeScripts`
 * lists them. Only mods from outside the store run any.
 */
function declaredScripts(mod) {
  if (!SCRIPT_SOURCES.has(mod?.source) || !Array.isArray(mod.scripts)) {
    return [];
  }

  // Mods added before scripts had options list plain paths.
  return mod.scripts.map(script =>
    typeof script === "string" ? { path: script, kind: "module" } : script
  );
}

/**
 * Owns the installed Zen Mods: the registry in `zen-themes.json`, the files
 * in `chrome/zen-themes/<id>/`, the generated `chrome/zen-themes.css` and the
 * updates from the store. One instance serves every window, so a change is
 * built once; windows only apply what needs their DOM (see ZenMods.mjs) and
 * listen to `zen-mods-update`.
 */
class nsZenModsManager {
  /** @type {Promise<void>|null} */
  #ready = null;

  /** @type {Record<string, object>} */
  #mods = {};

  /**
   * The mods that apply right now, with their preferences.
   *
   * @type {{id: string, name: string, sanitizedName: string, preferences: object[]}[]}
   */
  #appliedMods = [];

  /** Serializes registry writes and stylesheet rebuilds. */
  #queue = Promise.resolve();

  /** @type {Promise<object[]|null>|null} */
  #updateCheck = null;

  #autoUpdateScheduled = false;

  /**
   * Why a mod doesn't apply as it should, until it's fixed. Kept in memory:
   * the next session finds out again.
   *
   * @type {Map<string, {type: "missing-files"|"update-failed"|"script-failed", message?: string}>}
   */
  #errors = new Map();

  /**
   * The scripts that run right now: each version of a mod's scripts is
   * imported from a resource host of its own, so a changed file, or a file
   * it imports, is never served from the module registry.
   *
   * @type {Map<string, {hash: string, host: string, modules: object[]}>}
   */
  #scripts = new Map();

  /**
   * What each window started, so it can undo it even after the mod is gone.
   *
   * @type {WeakMap<Window, Map<string, {hash: string, modules: object[], api: object}>>}
   */
  #windowScripts = new WeakMap();

  /** @type {Set<string>} Mods turned off whose scripts can't be undone */
  #needsRestart = new Set();

  /**
   * The resource hosts whose `.uc.js` or `.uc.mjs` scripts ran in some
   * document: nothing takes those back but a restart.
   *
   * @type {Map<string, Set<string>>}
   */
  #ranHosts = new Map();

  /** @type {WeakMap<Document, Set<string>>} The scripts each document ran */
  #documentScripts = new WeakMap();

  #isWatchingDocuments = false;

  /** @type {Set<object>} Who asked to reload local mods when they change */
  #localWatchers = new Set();

  #isPollingLocalMods = false;

  get modsRootPath() {
    return PathUtils.join(PathUtils.profileDir, "chrome", "zen-themes");
  }

  get modsDataFile() {
    return PathUtils.join(PathUtils.profileDir, "zen-themes.json");
  }

  get #styleSheetPath() {
    return PathUtils.join(PathUtils.profileDir, "chrome", "zen-themes.css");
  }

  get #contentStyleSheetPath() {
    return PathUtils.join(
      PathUtils.profileDir,
      "chrome",
      "zen-themes-content.css"
    );
  }

  /** Whether mods may apply at all in this session. */
  get modsEnabled() {
    return (
      !Services.prefs.getBoolPref(DISABLE_ALL_PREF, false) &&
      !Services.appinfo.inSafeMode
    );
  }

  /**
   * Whether mod scripts may run. They have every power the browser has, so
   * they stay off until the user turns them on in about:config.
   */
  get scriptsEnabled() {
    return Services.prefs.getBoolPref(SCRIPTS_PREF, false) && this.modsEnabled;
  }

  /** @returns {object[]} The mods that apply right now */
  get appliedMods() {
    return this.#appliedMods;
  }

  /**
   * @param {string} modId
   * @returns {string} The folder that holds the mod's files: its own folder
   * for a local mod, one in the profile for a store mod
   */
  getModFolder(modId) {
    const mod = this.#mods[modId];

    if (mod?.source === "local") {
      return mod.path;
    }

    return PathUtils.join(this.modsRootPath, modId);
  }

  /**
   * @param {object} mod - An entry of the registry
   * @returns {string|null} The mod's style file, if it has one. Store mods
   * always keep it in `chrome.css`.
   */
  #styleFile(mod) {
    const relative = mod.stylePath === undefined ? "chrome.css" : mod.stylePath;

    return (
      relative &&
      PathUtils.join(this.getModFolder(mod.id), ...pathParts(relative))
    );
  }

  /**
   * @param {string} modId
   * @returns {"none"|"needs-approval"|"off"|"running"|"needs-restart"} What
   * the mod's scripts are doing
   */
  getScriptsState(modId) {
    const mod = this.#mods[modId];
    const host = this.#scripts.get(modId)?.host;
    const ranOutdated = [...(this.#ranHosts.get(modId) ?? [])].some(
      ranHost => ranHost !== host
    );

    if (this.#needsRestart.has(modId) || ranOutdated) {
      return "needs-restart";
    }

    if (!declaredScripts(mod).length) {
      return "none";
    }

    if (!this.#areScriptsApproved(mod)) {
      return "needs-approval";
    }

    return this.#scripts.has(modId) ? "running" : "off";
  }

  /**
   * @param {object} mod - An entry of the registry
   * @returns {boolean} Whether the user allowed the mod's scripts: any
   * version of a local mod's, but only the version they saw of a GitHub
   * mod's
   */
  #areScriptsApproved(mod) {
    return mod.source === "github"
      ? Boolean(mod.approvedScriptsHash) &&
          mod.approvedScriptsHash === mod.scriptsHash
      : Boolean(mod.scriptsApproved);
  }

  /**
   * Loads the registry and builds the stylesheet once per session. Every
   * public method waits for it, so callers don't need to.
   *
   * @returns {Promise<void>}
   */
  init() {
    this.#ready ??= this.#load();

    return this.#ready;
  }

  async #load() {
    // The old way to tell windows about changes; profiles still carry it.
    Services.prefs.clearUserPref("zen.mods.updated-value-observer");

    this.#mods = await this.#readRegistry();

    for (const pref of [DISABLE_ALL_PREF, SCRIPTS_PREF]) {
      Services.prefs.addObserver(pref, () => {
        this.#enqueue(() => this.#rebuild());
      });
    }

    this.#registerAgentSheet();

    // The sheet was loaded from disk at startup; only an outdated file needs
    // applying again.
    await this.#enqueue(() => this.#rebuild({ reload: false }));
  }

  /** @returns {Promise<Record<string, object>>} A copy of the installed mods */
  async getMods() {
    await this.init();

    return structuredClone(this.#mods);
  }

  /** @returns {Promise<object[]>} Copies of the installed mods, in load order */
  async getOrderedMods() {
    await this.init();

    return structuredClone(this.#orderedMods());
  }

  /**
   * @param {string} modId
   * @returns {Promise<boolean>}
   */
  async isModInstalled(modId) {
    await this.init();

    return Object.hasOwn(this.#mods, modId);
  }

  /**
   * @param {string} modId
   * @returns {{type: string, message?: string}|null} Why the mod doesn't apply
   * as it should
   */
  getModError(modId) {
    return this.#errors.get(modId) ?? null;
  }

  /**
   * Mods load in the order the user gave them, and the ones without one after
   * them, in the order they were installed. A later mod wins over an earlier
   * one when both style the same thing.
   *
   * @returns {object[]}
   */
  #orderedMods() {
    return Object.values(this.#mods)
      .map((mod, index) => ({ mod, index }))
      .sort(
        (first, second) =>
          (first.mod.order ?? Infinity) - (second.mod.order ?? Infinity) ||
          first.index - second.index
      )
      .map(({ mod }) => mod);
  }

  /**
   * @param {string[]} modIds - The installed mods, in the order to load them
   * @returns {Promise<void>}
   */
  async setModsOrder(modIds) {
    await this.init();

    await this.#mutate(mods => {
      for (const [index, modId] of modIds.entries()) {
        if (mods[modId]) {
          mods[modId].order = index;
        }
      }
    });
  }

  /**
   * Downloads a store mod again, keeping whether it's enabled and where it
   * loads. Fixes a mod whose files went missing or broke.
   *
   * @param {string} modId
   * @returns {Promise<void>}
   */
  async reinstallMod(modId) {
    await this.init();

    const mod = this.#mods[modId];

    if (mod?.source === "github") {
      await this.installGitHubMod(
        await this.#readGitHubCommit(gitHubSourceOf(mod), mod.sha)
      );
      return;
    }

    await this.installMod(await this.fetchStoreMod(modId));
  }

  /**
   * Finds the mod a GitHub repository, or a folder in it, holds at the
   * commit its branch points to now. Nothing is installed.
   *
   * @param {string} input - See parseGitHubSource
   * @returns {Promise<object>} What installGitHubMod takes
   */
  async fetchGitHubMod(input) {
    const source = parseGitHubSource(input);

    return this.#readGitHubCommit(
      source,
      await this.#resolveGitHubCommit(source)
    );
  }

  /**
   * Installs a mod `fetchGitHubMod` found, or updates the one installed from
   * the same place. Its files are a copy of that commit's.
   *
   * @param {object} found - What `fetchGitHubMod` returned
   * @param {object} [options]
   * @param {boolean} [options.scriptsApproved] - The user agreed to run the
   * mod's scripts as they are in that commit
   * @returns {Promise<string>} The mod's id
   */
  async installGitHubMod(found, { scriptsApproved = false } = {}) {
    await this.init();

    const existing = Object.values(this.#mods).find(
      mod =>
        mod.source === "github" &&
        mod.repo === found.repo &&
        (mod.folder ?? "") === found.folder
    );
    const modId =
      existing?.id ??
      `${GITHUB_ID_PREFIX}${Services.uuid.generateUUID().toString().slice(1, -1)}`;
    const staged = await this.#stageGitHub(modId, found);

    staged.mod.approvedScriptsHash = scriptsApproved
      ? staged.mod.scriptsHash
      : (existing?.approvedScriptsHash ?? null);

    await this.#commit([staged]);

    return modId;
  }

  /**
   * Installs the update of a GitHub mod that waits because its scripts
   * changed, now that the user allowed them.
   *
   * @param {string} modId
   * @returns {Promise<void>}
   */
  async approveUpdate(modId) {
    await this.init();

    const mod = this.#mods[modId];

    if (mod?.source !== "github" || !mod.pendingUpdate) {
      throw new Error(`[ZenMods]: ${modId} has no update waiting.`);
    }

    await this.installGitHubMod(
      await this.#readGitHubCommit(gitHubSourceOf(mod), mod.pendingUpdate.sha),
      { scriptsApproved: true }
    );
  }

  /**
   * @param {string} repo - "owner/repo"
   * @returns {string}
   */
  #gitHubApiUrl(repo) {
    return `${Services.prefs.getStringPref(GITHUB_API_URL_PREF)}repos/${repo}/`;
  }

  /**
   * @param {string} repo - "owner/repo"
   * @param {string} folder
   * @param {string} sha
   * @returns {string} Where the mod's files are, at that commit
   */
  #gitHubRawUrl(repo, folder, sha) {
    const path = folder ? `${encodePath(folder)}/` : "";

    return `${Services.prefs.getStringPref(GITHUB_RAW_URL_PREF)}${repo}/${sha}/${path}`;
  }

  /**
   * @param {{repo: string, ref: string|null}} source
   * @returns {Promise<string>} The commit the branch points to now
   */
  async #resolveGitHubCommit({ repo, ref }) {
    const api = this.#gitHubApiUrl(repo);
    const response = await this.#download(
      `${api}commits/${encodeURIComponent(ref ?? "HEAD")}`,
      [api],
      { Accept: "application/vnd.github.sha" }
    );
    const sha = new TextDecoder().decode(response).trim();

    if (!COMMIT_SHA_RE.test(sha)) {
      throw new Error(`[ZenMods]: GitHub returned no commit for ${repo}.`);
    }

    return sha;
  }

  /**
   * Reads the mod in a commit: which files it has and what its `theme.json`
   * declares. One without `theme.json` is named after its folder or
   * repository.
   *
   * @param {{repo: string, ref: string|null, folder: string}} source
   * @param {string} sha
   * @returns {Promise<object>}
   */
  async #readGitHubCommit({ repo, ref, folder }, sha) {
    if (!COMMIT_SHA_RE.test(sha)) {
      throw new Error(`[ZenMods]: Invalid commit: ${sha}`);
    }

    const api = this.#gitHubApiUrl(repo);
    const tree = JSON.parse(
      new TextDecoder().decode(
        await this.#download(`${api}git/trees/${sha}?recursive=1`, [api])
      )
    );

    if (!Array.isArray(tree?.tree) || tree.truncated) {
      throw new Error(`[ZenMods]: Could not list the files of ${repo}.`);
    }

    const prefix = folder ? `${folder}/` : "";
    const files = tree.tree
      .filter(
        entry =>
          entry?.type === "blob" &&
          typeof entry.path === "string" &&
          entry.path.startsWith(prefix)
      )
      .map(entry => ({
        path: entry.path.slice(prefix.length),
        size: Number(entry.size) || 0,
      }))
      .filter(({ path }) =>
        pathParts(path)?.every(
          part => !part.startsWith(".") && part !== "node_modules"
        )
      );
    const totalBytes = files.reduce((total, { size }) => total + size, 0);

    if (files.length > MAX_REMOTE_FILES || totalBytes > MAX_REMOTE_BYTES) {
      throw new Error(`[ZenMods]: ${repo} is too big for a mod.`);
    }

    const paths = new Set(files.map(({ path }) => path));
    const raw = this.#gitHubRawUrl(repo, folder, sha);
    const manifest = parseManifest(
      paths.has("theme.json")
        ? JSON.parse(
            new TextDecoder().decode(
              await this.#download(`${raw}theme.json`, [raw])
            )
          )
        : {}
    );

    for (const { path } of manifest.scripts) {
      if (!paths.has(path)) {
        throw new Error(`[ZenMods]: Script ${path} is missing.`);
      }
    }

    manifest.stylePath = await findStyle(manifest.stylePath, path =>
      paths.has(path)
    );

    if (manifest.contentStylePath && !paths.has(manifest.contentStylePath)) {
      console.warn(
        `[ZenMods]: ${manifest.contentStylePath} is missing in ${repo}, skipping the mod's page styles.`
      );
      manifest.contentStylePath = null;
    }

    if (
      !manifest.stylePath &&
      !manifest.contentStylePath &&
      !manifest.scripts.length
    ) {
      throw new Error(`[ZenMods]: ${repo} has neither styles nor scripts.`);
    }

    const [owner, repoName] = repo.split("/");

    return {
      ...manifest,
      name: manifest.name || folder.split("/").at(-1) || repoName,
      version: manifest.version || sha.slice(0, 7),
      author: manifest.author || owner,
      homepage: manifest.homepage || `https://github.com/${repo}`,
      preferences: paths.has(manifest.preferencesPath),
      source: "github",
      repo,
      ref,
      folder,
      sha,
      files: [...paths],
    };
  }

  /**
   * Downloads a GitHub mod's files, as they are in its commit, into a fresh
   * folder next to the installed ones.
   *
   * @param {string} modId
   * @param {object} found - What `#readGitHubCommit` returned
   * @returns {Promise<{mod: object, staging: string}>} The registry entry,
   * with the hash of its scripts, and the folder with the files
   */
  async #stageGitHub(modId, found) {
    const { repo, folder, sha, files } = found;
    await IOUtils.makeDirectory(this.modsRootPath, { ignoreExisting: true });

    const staging = await IOUtils.createUniqueDirectory(
      this.modsRootPath,
      ".github.staging"
    );
    const raw = this.#gitHubRawUrl(repo, folder, sha);
    const downloadFile = async path => {
      const target = PathUtils.join(staging, ...pathParts(path));

      await IOUtils.makeDirectory(PathUtils.parent(target), {
        ignoreExisting: true,
      });
      await IOUtils.write(
        target,
        await this.#download(`${raw}${encodePath(path)}`, [raw])
      );
    };

    const mod = { ...found, id: modId, scriptsHash: null };

    delete mod.files;

    try {
      for (let start = 0; start < files.length; start += PARALLEL_DOWNLOADS) {
        await Promise.all(
          files.slice(start, start + PARALLEL_DOWNLOADS).map(downloadFile)
        );
      }

      if (mod.scripts.length) {
        mod.scriptsHash = await this.#hashScripts(modId, staging);
      }
    } catch (error) {
      await IOUtils.remove(staging, { recursive: true, ignoreAbsent: true });

      throw error;
    }

    return { mod, staging };
  }

  /**
   * Reads and checks the `theme.json` of a mod in a folder of the user's.
   * Nothing is installed.
   *
   * @param {string} path - The mod's folder
   * @returns {Promise<object>} What the mod declares
   */
  async readLocalMod(path) {
    const manifest = parseManifest(
      await IOUtils.readJSON(PathUtils.join(path, "theme.json"))
    );
    const exists = relative =>
      IOUtils.exists(PathUtils.join(path, ...pathParts(relative)));

    for (const key of ["name", "version"]) {
      if (!manifest[key]) {
        throw new Error(`[ZenMods]: theme.json has no valid "${key}".`);
      }
    }

    for (const { path: script } of manifest.scripts) {
      if (!(await exists(script))) {
        throw new Error(`[ZenMods]: Script ${script} is missing.`);
      }
    }

    manifest.stylePath = await findStyle(manifest.stylePath, exists);

    if (
      manifest.contentStylePath &&
      !(await exists(manifest.contentStylePath))
    ) {
      console.warn(
        `[ZenMods]: ${manifest.contentStylePath} is missing, skipping the mod's page styles.`
      );
      manifest.contentStylePath = null;
    }

    if (
      !manifest.stylePath &&
      !manifest.contentStylePath &&
      !manifest.scripts.length
    ) {
      throw new Error("[ZenMods]: The mod has neither styles nor scripts.");
    }

    manifest.preferences = await exists(manifest.preferencesPath);

    return manifest;
  }

  /**
   * Adds a mod that lives in a folder of the user's. The folder isn't copied:
   * editing it and reloading the mod is how mods are made. Installing the
   * same folder again refreshes it.
   *
   * @param {string} path - The mod's folder
   * @param {object} [options]
   * @param {boolean} [options.scriptsApproved] - The user agreed to run the
   * mod's scripts
   * @returns {Promise<string>} The mod's id
   */
  async installLocalMod(path, { scriptsApproved = false } = {}) {
    await this.init();

    const manifest = await this.readLocalMod(path);
    const existing = Object.values(this.#mods).find(
      mod => mod.source === "local" && mod.path === path
    );
    const modId =
      existing?.id ??
      `${LOCAL_ID_PREFIX}${Services.uuid.generateUUID().toString().slice(1, -1)}`;

    await this.#mirrorLocalMod(modId, path, Boolean(manifest.contentStylePath));

    await this.#mutate(mods => {
      mods[modId] = {
        ...manifest,
        id: modId,
        source: "local",
        path,
        enabled: existing?.enabled ?? true,
        order: existing?.order,
        scriptsApproved: scriptsApproved || Boolean(existing?.scriptsApproved),
      };
      this.#errors.delete(modId);
    });

    return modId;
  }

  /**
   * Content processes may only read the profile's chrome folder, so a local
   * mod with styles for pages gets a copy there. Its styles for Zen and its
   * scripts keep coming from the user's folder.
   *
   * @param {string} modId
   * @param {string} path - The mod's folder
   * @param {boolean} hasContentStyles
   */
  async #mirrorLocalMod(modId, path, hasContentStyles) {
    const mirror = PathUtils.join(this.modsRootPath, modId);

    if (!hasContentStyles) {
      await IOUtils.remove(mirror, { recursive: true, ignoreAbsent: true });
      return;
    }

    await IOUtils.makeDirectory(this.modsRootPath, { ignoreExisting: true });

    const staging = await IOUtils.createUniqueDirectory(
      this.modsRootPath,
      `.${modId}.staging`
    );

    try {
      for (const { path: file } of await listModFiles(
        path,
        null,
        MAX_LOCAL_FILES
      )) {
        const target = PathUtils.join(
          staging,
          ...PathUtils.splitRelative(file.slice(path.length + 1))
        );

        await IOUtils.makeDirectory(PathUtils.parent(target), {
          ignoreExisting: true,
        });
        await IOUtils.copy(file, target);
      }

      await this.#replaceFolder(staging, mirror);
    } catch (error) {
      await IOUtils.remove(staging, { recursive: true, ignoreAbsent: true });

      throw error;
    }
  }

  /**
   * Reads a local mod's folder again: its `theme.json`, styles and scripts.
   *
   * @param {string} modId
   * @returns {Promise<void>}
   */
  async reloadLocalMod(modId) {
    await this.init();

    const mod = this.#mods[modId];

    if (mod?.source !== "local") {
      throw new Error(`[ZenMods]: ${modId} is not a local mod.`);
    }

    await this.installLocalMod(mod.path);
  }

  /**
   * Reloads local mods when their files change, for as long as someone
   * watches. Checking the folders costs a little, so the Library only
   * watches while it shows the mods.
   *
   * @returns {() => void} Stops watching
   */
  watchLocalMods() {
    const watcher = {};

    this.#localWatchers.add(watcher);

    if (!this.#isPollingLocalMods) {
      this.#pollLocalMods();
    }

    return () => this.#localWatchers.delete(watcher);
  }

  async #pollLocalMods() {
    const signatures = new Map();

    this.#isPollingLocalMods = true;
    await this.init();

    while (this.#localWatchers.size) {
      for (const mod of Object.values(this.#mods)) {
        if (mod.source !== "local" || mod.enabled === false) {
          continue;
        }

        let signature;

        try {
          const files = await listModFiles(mod.path, null, MAX_LOCAL_FILES);

          signature = files
            .map(
              ({ path, info }) => `${path}:${info.lastModified}:${info.size}`
            )
            .join("\n");
        } catch (error) {
          // A folder that's gone, or too big, changes again when it's fixed.
          signature = String(error);
        }

        const previous = signatures.get(mod.id);

        signatures.set(mod.id, signature);

        if (previous === undefined || previous === signature) {
          continue;
        }

        try {
          await this.reloadLocalMod(mod.id);
        } catch (error) {
          console.warn(`[ZenMods]: Could not reload ${mod.name}:`, error);
        }
      }

      await new Promise(resolve => setTimeout(resolve, LOCAL_POLL_MS));
    }

    this.#isPollingLocalMods = false;
  }

  /**
   * Lets a mod's scripts run once scripts are allowed: any version of a
   * local mod's, the installed version of a GitHub mod's.
   *
   * @param {string} modId
   * @returns {Promise<void>}
   */
  async approveScripts(modId) {
    await this.init();

    await this.#mutate(mods => {
      const mod = mods[modId];

      switch (mod?.source) {
        case "local": {
          mod.scriptsApproved = true;
          break;
        }

        case "github": {
          mod.approvedScriptsHash = mod.scriptsHash;
          break;
        }

        default: {
          throw new Error(`[ZenMods]: ${modId} can't run scripts.`);
        }
      }
    });
  }

  /**
   * Starts in a window the scripts that should run and stops the ones that
   * shouldn't anymore. Windows call it when they open and on every change.
   *
   * @param {Window} win
   */
  syncScripts(win) {
    let started = this.#windowScripts.get(win);
    let changed = false;

    if (!started) {
      started = new Map();
      this.#windowScripts.set(win, started);
    }

    for (const [modId, previous] of started) {
      if (this.#scripts.get(modId)?.hash === previous.hash) {
        continue;
      }

      if (!this.#runHook(modId, previous.modules, "uninit", win)) {
        this.#needsRestart.add(modId);
        changed = true;
      }

      previous.api.dispose();
      started.delete(modId);
    }

    for (const [modId, { hash, modules }] of this.#scripts) {
      if (started.has(modId) || !modules.length) {
        continue;
      }

      const mod = this.#mods[modId];
      const api = new lazy.ZenModAPI(
        win,
        { id: modId, name: mod.name, version: mod.version },
        error => this.#reportScriptError(modId, error)
      );

      changed ||= !this.#runHook(modId, modules, "init", win, api);
      started.set(modId, { hash, modules, api });
    }

    if (changed) {
      // Not from inside the observers that called us.
      Promise.resolve().then(() =>
        Services.obs.notifyObservers(null, ZEN_MODS_UPDATE_TOPIC)
      );
    }
  }

  /**
   * Stops the scripts a closing window started.
   *
   * @param {Window} win
   */
  forgetWindow(win) {
    for (const [modId, { modules, api }] of this.#windowScripts.get(win) ??
      []) {
      this.#runHook(modId, modules, "uninit", win);
      api.dispose();
    }

    this.#windowScripts.delete(win);
  }

  /**
   * Calls `init` or `uninit` of a mod's modules for a window. A script that
   * throws can't break the window or the other mods.
   *
   * @param {string} modId
   * @param {object[]} modules
   * @param {"init"|"uninit"} hook
   * @param {Window} win
   * @param {object} [api] - What `init` gets from Zen for this window
   * @returns {boolean} Whether every module had the hook and it went well
   */
  #runHook(modId, modules, hook, win, api) {
    let complete = true;

    for (const module of modules) {
      if (typeof module[hook] !== "function") {
        // Without init a module just has nothing to do per window.
        complete = complete && hook === "init";
        continue;
      }

      try {
        const result = module[hook](win, api);

        // An async init reports its failure when it comes.
        if (typeof result?.catch === "function") {
          result.catch(error => this.#reportScriptError(modId, error));
        }
      } catch (error) {
        console.error(`[ZenMods]: ${hook} of ${modId} failed:`, error);

        complete = false;
        this.#errors.set(modId, {
          type: "script-failed",
          message: String(error?.message ?? error),
        });
      }
    }

    return complete;
  }

  /**
   * Marks a mod whose script failed after it started, and tells the UI.
   *
   * @param {string} modId
   * @param {*} error
   */
  #reportScriptError(modId, error) {
    console.error(`[ZenMods]: A script of ${modId} failed:`, error);

    this.#errors.set(modId, {
      type: "script-failed",
      message: String(error?.message ?? error),
    });
    Services.obs.notifyObservers(null, ZEN_MODS_UPDATE_TOPIC);
  }

  /**
   * Imports the scripts of every enabled mod whose scripts the user approved,
   * while scripts are allowed, and forgets the ones that shouldn't run
   * anymore. Only local mods run scripts: the store doesn't review them yet.
   */
  async #loadScripts() {
    const wanted = this.scriptsEnabled
      ? this.#orderedMods().filter(
          mod =>
            mod.enabled !== false &&
            this.#areScriptsApproved(mod) &&
            declaredScripts(mod).length
        )
      : [];
    const wantedIds = new Set(wanted.map(mod => mod.id));

    for (const [modId, loaded] of this.#scripts) {
      if (!wantedIds.has(modId)) {
        this.#forgetScripts(modId, loaded);
        this.#scripts.delete(modId);
      }
    }

    for (const mod of wanted) {
      const folder = this.getModFolder(mod.id);
      const loaded = this.#scripts.get(mod.id);
      let host = null;

      try {
        const hash = await this.#hashScripts(mod.id, folder);

        if (loaded?.hash === hash) {
          continue;
        }

        if (mod.source === "github" && hash !== mod.approvedScriptsHash) {
          throw new Error("The scripts changed since they were allowed.");
        }

        const directory = Cc["@mozilla.org/file/local;1"].createInstance(
          Ci.nsIFile
        );

        directory.initWithPath(folder);
        host = `${SCRIPT_HOST_PREFIX}${hash.slice(0, 16)}`;
        lazy.resProtocol.setSubstitution(
          host,
          Services.io.newFileURI(directory)
        );

        const scripts = declaredScripts(mod).map(script => ({
          ...script,
          url: `resource://${host}/${encodePath(script.path)}`,
        }));
        const modules = scripts
          .filter(({ kind }) => kind === "module")
          .map(({ url }) => ChromeUtils.importESModule(url));
        const documentScripts = scripts
          .filter(({ kind }) => kind !== "module")
          .map(script => ({
            ...script,
            include: urlPatterns(script.include),
            exclude: urlPatterns(script.exclude),
          }));

        if (loaded) {
          this.#forgetScripts(mod.id, loaded);
        }

        this.#scripts.set(mod.id, { hash, host, modules, documentScripts });
        this.#needsRestart.delete(mod.id);

        if (this.#errors.get(mod.id)?.type === "script-failed") {
          this.#errors.delete(mod.id);
        }

        if (documentScripts.length) {
          this.#runInOpenDocuments();
        }
      } catch (error) {
        console.error(
          `[ZenMods]: Could not load the scripts of ${mod.name} (${mod.id}):`,
          error
        );

        // A version that loaded before keeps running.
        if (host && host !== loaded?.host) {
          lazy.resProtocol.setSubstitution(host, null);
        }

        this.#errors.set(mod.id, {
          type: "script-failed",
          message: String(error?.message ?? error),
        });
      }
    }
  }

  /**
   * Stops a mod's scripts from reaching more documents. The resource host
   * stays while code that ran from it may still import its files.
   *
   * @param {string} modId
   * @param {{host: string}} loaded
   */
  #forgetScripts(modId, { host }) {
    if (!this.#ranHosts.get(modId)?.has(host)) {
      lazy.resProtocol.setSubstitution(host, null);
    }
  }

  /**
   * @param {string} url - A document's URL
   * @returns {{modId: string, host: string, script: object}[]} The `.uc.js`
   * and `.uc.mjs` scripts meant for it, in the order they load
   */
  #documentScriptsFor(url) {
    const matching = [];

    for (const [modId, { host, documentScripts }] of this.#scripts) {
      for (const script of documentScripts) {
        if (script.include?.test(url) && !script.exclude?.test(url)) {
          matching.push({ modId, host, script });
        }
      }
    }

    return matching.sort(
      (first, second) => first.script.loadOrder - second.script.loadOrder
    );
  }

  /**
   * Runs `.uc.js` and `.uc.mjs` scripts the way userChrome.js loaders do:
   * once a document they're meant for is parsed, classic scripts in its
   * global and modules in its own module map. A script that throws can't
   * stop the others.
   *
   * @param {Document} doc
   */
  #runDocumentScripts(doc) {
    let ran = this.#documentScripts.get(doc);
    let failed = false;

    if (!ran) {
      ran = new Set();
      this.#documentScripts.set(doc, ran);
    }

    for (const { modId, host, script } of this.#documentScriptsFor(doc.URL)) {
      if (ran.has(script.url)) {
        continue;
      }

      ran.add(script.url);

      if (!this.#ranHosts.has(modId)) {
        this.#ranHosts.set(modId, new Set());
      }

      this.#ranHosts.get(modId).add(host);

      try {
        if (script.kind === "uc.js") {
          Services.scriptloader.loadSubScriptWithOptions(script.url, {
            target: doc.documentGlobal,
            ignoreCache: true,
          });
        } else {
          doc.documentGlobal.ChromeUtils.importESModule(script.url, {
            global: "current",
          });
        }
      } catch (error) {
        console.error(
          `[ZenMods]: ${script.path} of ${modId} failed in ${doc.URL}:`,
          error
        );

        failed = true;
        this.#errors.set(modId, {
          type: "script-failed",
          message: String(error?.message ?? error),
        });
      }
    }

    if (failed) {
      Services.obs.notifyObservers(null, ZEN_MODS_UPDATE_TOPIC);
    }
  }

  /**
   * Runs document scripts in the documents already open, and in every one
   * parsed from now on.
   */
  #runInOpenDocuments() {
    const runWhenParsed = doc => {
      if (doc.readyState === "loading") {
        doc.addEventListener(
          "DOMContentLoaded",
          () => this.#runDocumentScripts(doc),
          { once: true }
        );
      } else {
        this.#runDocumentScripts(doc);
      }
    };

    if (!this.#isWatchingDocuments) {
      this.#isWatchingDocuments = true;
      Services.obs.addObserver(doc => {
        if (
          doc.nodePrincipal?.isSystemPrincipal &&
          doc.URL !== "about:blank" &&
          this.#documentScriptsFor(doc.URL).length
        ) {
          runWhenParsed(doc);
        }
      }, "document-element-inserted");
    }

    for (const win of Services.wm.getEnumerator(null)) {
      runWhenParsed(win.document);
    }
  }

  /**
   * Hashes every script file in a mod's folder, the ones its scripts import
   * included, so any change gives the scripts a new resource host.
   *
   * @param {string} modId
   * @param {string} folder
   * @returns {Promise<string>} A hex SHA-256
   */
  async #hashScripts(modId, folder) {
    const files = await listModFiles(folder, SCRIPT_FILE_RE, MAX_SCRIPT_FILES);
    const encoder = new TextEncoder();
    const chunks = [encoder.encode(modId)];

    for (const { path } of files) {
      chunks.push(
        encoder.encode(`\0${path.slice(folder.length)}\0`),
        await IOUtils.read(path)
      );
    }

    const bytes = new Uint8Array(
      chunks.reduce((total, chunk) => total + chunk.length, 0)
    );
    let offset = 0;

    for (const chunk of chunks) {
      bytes.set(chunk, offset);
      offset += chunk.length;
    }

    const digest = await crypto.subtle.digest("SHA-256", bytes);

    return Array.from(new Uint8Array(digest), byte =>
      byte.toString(16).padStart(2, "0")
    ).join("");
  }

  /**
   * Reads the preferences a mod declares, without the ones disabled on this
   * operating system.
   *
   * @param {object} mod - An entry of the registry
   * @returns {Promise<object[]>}
   */
  async getModPreferences(mod) {
    if (!mod?.preferences) {
      return [];
    }

    let preferences;

    try {
      preferences = await IOUtils.readJSON(
        PathUtils.join(
          this.getModFolder(mod.id),
          ...pathParts(mod.preferencesPath ?? "preferences.json")
        )
      );
    } catch (error) {
      if (!isNotFound(error)) {
        console.error(
          `[ZenMods]: Error reading the preferences of ${mod.name}:`,
          error
        );
      }

      return [];
    }

    if (!Array.isArray(preferences)) {
      console.warn(
        `[ZenMods]: The preferences of ${mod.name} are not a list, skipping.`
      );

      return [];
    }

    const os = OS_NAMES[Services.appinfo.OS];
    const valid = [];

    for (const preference of preferences) {
      const hasProperty =
        typeof preference?.property === "string" &&
        Boolean(preference.property);

      if (!hasProperty && !LABEL_TYPES.has(preference?.type)) {
        console.warn(
          `[ZenMods]: A preference of ${mod.name} has no property, skipping.`
        );
        continue;
      }

      if (
        Array.isArray(preference.disabledOn) &&
        preference.disabledOn.includes(os)
      ) {
        continue;
      }

      valid.push(
        hasProperty ? preference : { ...preference, property: undefined }
      );
    }

    return valid;
  }

  /**
   * @returns {Promise<object[]>} What the store publishes, the most recently
   * updated first. Only data: nothing is installed.
   */
  async fetchStoreIndex() {
    const url = `${Services.prefs.getStringPref(STORE_URL_PREF)}themes.json`;
    const index = JSON.parse(
      new TextDecoder().decode(await this.#download(url))
    );

    if (!index || typeof index !== "object") {
      throw new Error("[ZenMods]: The mods store index is invalid.");
    }

    const entries = [];

    for (const [modId, mod] of Object.entries(index)) {
      try {
        this.#validateStoreMod(mod, modId);
        entries.push(mod);
      } catch (error) {
        console.warn(
          `[ZenMods]: Invalid store entry ${modId}, skipping.`,
          error
        );
      }
    }

    return entries.sort((first, second) =>
      String(second.updatedAt ?? "").localeCompare(
        String(first.updatedAt ?? "")
      )
    );
  }

  /**
   * @param {*} url
   * @returns {boolean} Whether the URL is the store's, like the images of
   * its mods: chrome only loads those
   */
  isStoreUrl(url) {
    try {
      this.#assertAllowedUrl(String(url), this.#storeUrls());

      return true;
    } catch {
      return false;
    }
  }

  /**
   * Fetches what the store publishes about a mod. The result is only data:
   * nothing is downloaded or installed yet.
   *
   * @param {string} modId
   * @returns {Promise<object>}
   */
  async fetchStoreMod(modId) {
    if (typeof modId !== "string" || !STORE_MOD_ID_RE.test(modId)) {
      throw new Error(`[ZenMods]: Invalid mod id: ${modId}`);
    }

    const url = `${Services.prefs.getStringPref(STORE_URL_PREF)}themes/${modId}/theme.json`;
    const mod = JSON.parse(new TextDecoder().decode(await this.#download(url)));

    this.#validateStoreMod(mod, modId);

    return mod;
  }

  /**
   * Installs a mod the store published, or replaces it if it's there. The
   * files are downloaded first and only replace the installed ones once all
   * of them arrived, so a failed download never breaks the installed mod.
   *
   * @param {object} mod - What `fetchStoreMod` returned
   * @returns {Promise<void>}
   */
  async installMod(mod) {
    this.#validateStoreMod(mod, mod?.id);

    await this.init();

    const staging = await this.#stage(mod);

    await this.#commit([{ mod: storeEntry(mod), staging }]);
  }

  /**
   * Removes a mod, its files and the preferences it declared, unless another
   * installed mod declares the same preference.
   *
   * @param {string} modId
   * @returns {Promise<void>}
   */
  async uninstallMod(modId) {
    await this.init();

    const mod = this.#mods[modId];

    if (!mod) {
      return;
    }

    const preferences = await this.getModPreferences(mod);

    const folder = this.getModFolder(modId);

    await this.#mutate(async mods => {
      delete mods[modId];
      this.#errors.delete(modId);

      // A local mod's folder is the user's; only its copy in the profile goes.
      await IOUtils.remove(
        mod.source === "local"
          ? PathUtils.join(this.modsRootPath, modId)
          : folder,
        { recursive: true, ignoreAbsent: true }
      );
    });

    const stillUsed = new Set();

    for (const other of Object.values(this.#mods)) {
      for (const { property } of await this.getModPreferences(other)) {
        stillUsed.add(property);
      }
    }

    for (const { property } of preferences) {
      if (property && !stillUsed.has(property)) {
        Services.prefs.clearUserPref(property);
      }
    }
  }

  /**
   * @param {string} modId
   * @param {boolean} enabled
   * @returns {Promise<void>}
   */
  async setModEnabled(modId, enabled) {
    await this.init();

    await this.#mutate(mods => {
      if (!mods[modId]) {
        throw new Error(`[ZenMods]: Mod ${modId} is not installed.`);
      }

      mods[modId].enabled = enabled;
    });
  }

  /**
   * Updates every store mod that has a newer version and every GitHub mod
   * whose branch moved, and reinstalls the ones whose files are missing.
   * Concurrent calls share the same check.
   *
   * @returns {Promise<object[]|null>} The updated mods, or null if the store
   * could not be reached
   */
  checkForUpdates() {
    this.#updateCheck ??= this.#runUpdateCheck().finally(() => {
      this.#updateCheck = null;
    });

    return this.#updateCheck;
  }

  /**
   * Checks for updates once per session, when the user allows it and enough
   * days passed. Every window calls this; only the first call counts.
   */
  scheduleAutoUpdate() {
    if (this.#autoUpdateScheduled) {
      return;
    }

    this.#autoUpdateScheduled = true;

    if (
      Services.prefs.getStringPref(MILESTONE_PREF, "") !==
      Services.appinfo.version
    ) {
      Services.prefs.setStringPref(MILESTONE_PREF, Services.appinfo.version);
      Services.prefs.clearUserPref(LAST_UPDATE_PREF);
    }

    const lastUpdate = Services.prefs.getIntPref(LAST_UPDATE_PREF, -1);
    const daysSinceUpdate =
      (Math.floor(Date.now() / 1000) - lastUpdate) / SECONDS_PER_DAY;
    const isDue =
      Services.prefs.getBoolPref(AUTO_UPDATE_PREF, true) &&
      daysSinceUpdate >= Services.prefs.getIntPref(AUTO_UPDATE_DAYS_PREF);

    if (!isDue && lastUpdate >= 0) {
      return;
    }

    ChromeUtils.idleDispatch(() => this.checkForUpdates(), { timeout: 1000 });
  }

  async #runUpdateCheck() {
    await this.init();

    const staged = [];
    const pending = [];
    const storeReached = await this.#stageStoreUpdates(staged);

    for (const mod of Object.values(this.#mods)) {
      if (mod.source !== "github") {
        continue;
      }

      try {
        await this.#stageGitHubUpdate(mod, staged, pending);
      } catch (error) {
        console.error(
          `[ZenMods]: Could not update ${mod.name} (${mod.id}), keeping the installed version:`,
          error
        );

        this.#errors.set(mod.id, {
          type: "update-failed",
          message: String(error?.message ?? error),
        });
      }
    }

    if (pending.length) {
      await this.#mutate(mods => {
        for (const { modId, update } of pending) {
          if (mods[modId]) {
            mods[modId].pendingUpdate = update;
          }
        }
      });
    }

    if (staged.length) {
      await this.#commit(staged);
    } else if (!pending.length) {
      // Nothing was rebuilt, but the failed updates are news.
      Services.obs.notifyObservers(null, ZEN_MODS_UPDATE_TOPIC);
    }

    if (!storeReached) {
      return null;
    }

    Services.prefs.setIntPref(LAST_UPDATE_PREF, Math.floor(Date.now() / 1000));

    return staged.map(({ mod }) => mod);
  }

  /**
   * Stages the store mods that have a newer version, and the ones whose
   * files are missing.
   *
   * @param {object[]} staged - Where staged mods go
   * @returns {Promise<boolean>} Whether the store could be reached, if any
   * mod comes from it
   */
  async #stageStoreUpdates(staged) {
    const storeMods = Object.values(this.#mods).filter(mod => !mod.source);

    if (!storeMods.length) {
      return true;
    }

    let index;

    try {
      const url = `${Services.prefs.getStringPref(STORE_URL_PREF)}themes.json`;

      index = JSON.parse(new TextDecoder().decode(await this.#download(url)));
    } catch (error) {
      console.error("[ZenMods]: Could not fetch the mods store:", error);

      return false;
    }

    if (!index || typeof index !== "object") {
      console.error("[ZenMods]: The mods store index is invalid.");

      return false;
    }

    for (const mod of storeMods) {
      const latest = index[mod.id];

      if (!latest) {
        continue;
      }

      try {
        this.#validateStoreMod(latest, mod.id);

        const isNewer =
          Services.vc.compare(latest.version, mod.version ?? "0.0.0") > 0;

        if (!isNewer && (await IOUtils.exists(this.#styleFile(mod)))) {
          continue;
        }

        console.warn(
          `[ZenMods]: Updating ${mod.name} (${mod.id}) from ${mod.version} to ${latest.version}.`
        );

        staged.push({
          mod: storeEntry(latest),
          staging: await this.#stage(latest),
        });
      } catch (error) {
        console.error(
          `[ZenMods]: Could not update ${mod.name} (${mod.id}), keeping the installed version:`,
          error
        );

        this.#errors.set(mod.id, {
          type: "update-failed",
          message: String(error?.message ?? error),
        });
      }
    }

    return true;
  }

  /**
   * Stages a GitHub mod whose branch moved, or whose files are missing. An
   * update that changes scripts the user allowed waits until they allow it.
   *
   * @param {object} mod - An entry of the registry
   * @param {object[]} staged - Where staged mods go
   * @param {object[]} pending - Where updates that wait go
   */
  async #stageGitHubUpdate(mod, staged, pending) {
    const source = gitHubSourceOf(mod);
    const sha = await this.#resolveGitHubCommit(source);
    const stylePath = this.#styleFile(mod);
    const hasFiles = !stylePath || (await IOUtils.exists(stylePath));

    if ((sha === mod.sha && hasFiles) || sha === mod.pendingUpdate?.sha) {
      return;
    }

    const update = await this.#stageGitHub(
      mod.id,
      await this.#readGitHubCommit(source, sha)
    );
    const { scriptsHash } = update.mod;

    if (
      mod.approvedScriptsHash &&
      scriptsHash &&
      scriptsHash !== mod.approvedScriptsHash
    ) {
      console.warn(
        `[ZenMods]: The update of ${mod.name} (${mod.id}) changes its scripts, waiting for the user to allow them.`
      );

      await IOUtils.remove(update.staging, {
        recursive: true,
        ignoreAbsent: true,
      });
      pending.push({
        modId: mod.id,
        update: { sha, version: update.mod.version },
      });

      return;
    }

    update.mod.approvedScriptsHash = mod.approvedScriptsHash ?? null;
    staged.push(update);
  }

  /**
   * Checks the parts of a store entry that end up in paths and URLs.
   *
   * @param {object} mod
   * @param {string} expectedId - The id the mod was requested with
   */
  #validateStoreMod(mod, expectedId) {
    if (!mod || typeof mod !== "object") {
      throw new Error("[ZenMods]: The mod data is not an object.");
    }

    if (mod.id !== expectedId || !STORE_MOD_ID_RE.test(mod.id)) {
      throw new Error(`[ZenMods]: Unexpected mod id: ${mod.id}`);
    }

    for (const key of ["name", "style", "version"]) {
      if (typeof mod[key] !== "string" || !mod[key]) {
        throw new Error(`[ZenMods]: Mod ${mod.id} has no valid "${key}".`);
      }
    }
  }

  /**
   * Downloads a store mod's files into a fresh folder next to the installed
   * ones.
   *
   * @param {object} mod - A validated store entry
   * @returns {Promise<string>} The folder with the downloaded files
   */
  async #stage(mod) {
    await IOUtils.makeDirectory(this.modsRootPath, { ignoreExisting: true });

    const staging = await IOUtils.createUniqueDirectory(
      this.modsRootPath,
      `.${mod.id}.staging`
    );
    const files = [
      { name: "chrome.css", url: mod.style, required: true },
      { name: "preferences.json", url: mod.preferences, required: true },
      { name: "readme.md", url: mod.readme, required: false },
    ];

    try {
      for (const { name, url, required } of files) {
        if (!url) {
          continue;
        }

        try {
          await IOUtils.write(
            PathUtils.join(staging, name),
            await this.#download(url)
          );
        } catch (error) {
          if (required) {
            throw error;
          }

          console.warn(
            `[ZenMods]: Could not download ${name} of ${mod.name}, skipping.`,
            error
          );
        }
      }
    } catch (error) {
      await IOUtils.remove(staging, { recursive: true, ignoreAbsent: true });

      throw error;
    }

    return staging;
  }

  /**
   * Puts staged mods in place and records them, keeping whether each one was
   * enabled and where it loads.
   *
   * @param {{mod: object, staging: string}[]} staged
   */
  async #commit(staged) {
    await this.#mutate(async mods => {
      for (const { mod, staging } of staged) {
        const previous = mods[mod.id];

        await this.#replaceFolder(staging, this.getModFolder(mod.id));

        mods[mod.id] = {
          ...mod,
          enabled: previous?.enabled ?? true,
          order: previous?.order,
        };
        this.#errors.delete(mod.id);
      }
    });
  }

  async #replaceFolder(staging, folder) {
    const previous = `${staging}.previous`;
    const hadFolder = await IOUtils.exists(folder);

    if (hadFolder) {
      await IOUtils.move(folder, previous);
    }

    try {
      await IOUtils.move(staging, folder);
    } catch (error) {
      if (hadFolder) {
        await IOUtils.move(previous, folder);
      }

      throw error;
    }

    await IOUtils.remove(previous, { recursive: true, ignoreAbsent: true });
  }

  /** @returns {string[]} Where store files may come from */
  #storeUrls() {
    return [
      Services.prefs.getStringPref(STORE_URL_PREF),
      Services.prefs.getStringPref(STORE_ASSETS_URL_PREF),
    ];
  }

  /**
   * Mod files only come over HTTPS from where they're expected, also after
   * redirects.
   *
   * @param {string} url
   * @param {string[]} allowed - URL prefixes
   */
  #assertAllowedUrl(url, allowed) {
    const parsed = URL.parse(url);

    if (parsed?.protocol !== "https:") {
      throw new Error(`[ZenMods]: Refusing a non-HTTPS mod URL: ${url}`);
    }

    if (!allowed.some(prefix => parsed.href.startsWith(prefix))) {
      throw new Error(`[ZenMods]: Refusing a mod URL from elsewhere: ${url}`);
    }
  }

  /**
   * @param {string} url
   * @param {string[]} [allowed] - URL prefixes it may come from; the store
   * by default
   * @param {Record<string, string>} [headers]
   * @returns {Promise<Uint8Array>}
   */
  async #download(url, allowed = this.#storeUrls(), headers = {}) {
    this.#assertAllowedUrl(url, allowed);

    let lastError;

    for (let attempt = 1; attempt <= DOWNLOAD_ATTEMPTS; attempt++) {
      try {
        const response = await fetch(url, { headers });

        if (!response.ok) {
          throw new Error(`HTTP ${response.status} for ${url}`);
        }

        this.#assertAllowedUrl(response.url, allowed);

        if (Number(response.headers.get("content-length")) > MAX_FILE_BYTES) {
          throw new Error(`${url} is larger than ${MAX_FILE_BYTES} bytes`);
        }

        const buffer = await response.arrayBuffer();

        if (buffer.byteLength > MAX_FILE_BYTES) {
          throw new Error(`${url} is larger than ${MAX_FILE_BYTES} bytes`);
        }

        return new Uint8Array(buffer);
      } catch (error) {
        lastError = error;

        if (attempt < DOWNLOAD_ATTEMPTS) {
          console.warn(
            `[ZenMods]: Download failed (attempt ${attempt} of ${DOWNLOAD_ATTEMPTS}), retrying in ${RETRY_DELAY_MS}ms.`,
            url,
            error
          );

          await new Promise(resolve => setTimeout(resolve, RETRY_DELAY_MS));
        }
      }
    }

    throw lastError;
  }

  async #readRegistry() {
    let data;

    try {
      data = await IOUtils.readJSON(this.modsDataFile);
    } catch (error) {
      if (isNotFound(error)) {
        await this.#writeRegistry({});

        return {};
      }

      console.warn("[ZenMods]: Could not read the mods data file:", error);
    }

    if (!data || typeof data !== "object" || Array.isArray(data)) {
      await this.#writeRegistry({});

      Services.wm
        .getMostRecentWindow("navigator:browser")
        ?.gZenUIManager?.showToast("zen-themes-corrupted", { timeout: 8000 });

      return {};
    }

    const mods = {};

    for (const [id, mod] of Object.entries(data)) {
      if (!mod || typeof mod !== "object") {
        console.warn(`[ZenMods]: Invalid entry for mod ${id}, skipping.`);
        continue;
      }

      mods[id] = { ...mod, id };
    }

    return mods;
  }

  async #writeRegistry(mods) {
    await IOUtils.writeJSON(this.modsDataFile, mods, {
      tmpPath: `${this.modsDataFile}.tmp`,
    });
  }

  /**
   * Runs a task after every write and rebuild queued before it.
   *
   * @param {() => Promise<*>} task
   * @returns {Promise<*>}
   */
  #enqueue(task) {
    const run = this.#queue.then(task);

    this.#queue = run.catch(() => {});

    return run;
  }

  /**
   * Changes the registry, saves it and rebuilds the stylesheet, one change at
   * a time.
   *
   * @param {(mods: Record<string, object>) => *} change
   * @returns {Promise<*>}
   */
  #mutate(change) {
    return this.#enqueue(async () => {
      const result = await change(this.#mods);

      await this.#writeRegistry(this.#mods);
      await this.#rebuild();

      return result;
    });
  }

  /**
   * Writes `zen-themes.css` as one `@import` per enabled mod, so each mod is
   * its own sheet: a mod with broken CSS can't swallow the ones after it,
   * and errors point at the mod's own file.
   *
   * @param {object} [options]
   * @param {boolean} [options.reload] - Apply the sheet even if the file
   * didn't change, because a mod's own file may have.
   */
  async #rebuild({ reload = true } = {}) {
    const mods = this.modsEnabled
      ? this.#orderedMods().filter(mod => mod.enabled !== false)
      : [];
    const applied = [];

    let content = STYLESHEET_HEADER;
    let pageContent = STYLESHEET_HEADER;

    for (const mod of mods) {
      const stylePath = this.#styleFile(mod);
      const hasStyles = Boolean(stylePath) && (await IOUtils.exists(stylePath));

      // Page styles of every mod come from the profile, local mods' too,
      // through their copy there.
      if (mod.contentStylePath) {
        pageContent += `@import url("zen-themes/${encodeURIComponent(mod.id)}/${encodePath(mod.contentStylePath)}");\n`;
      }

      if (!hasStyles && !mod.contentStylePath && !declaredScripts(mod).length) {
        console.warn(
          `[ZenMods]: ${mod.name} (${mod.id}) has no styles, skipping.`
        );

        this.#errors.set(mod.id, { type: "missing-files" });
        continue;
      }

      if (this.#errors.get(mod.id)?.type === "missing-files") {
        this.#errors.delete(mod.id);
      }

      if (hasStyles) {
        // Store mods live next to the sheet; local ones wherever the user
        // keeps them.
        const url =
          mod.source === "local"
            ? PathUtils.toFileURI(stylePath)
            : `zen-themes/${encodeURIComponent(mod.id)}/${encodePath(mod.stylePath ?? "chrome.css")}`;

        content += `@import url("${url}");\n`;
      }

      applied.push({
        id: mod.id,
        name: mod.name,
        sanitizedName: sanitizeModName(mod.name),
        preferences: await this.getModPreferences(mod),
      });
    }

    this.#setDefaults(applied);
    this.#appliedMods = applied;

    await this.#writeStylesheet(content, reload);
    await this.#writeContentStylesheet(
      pageContent,
      reload && mods.some(mod => mod.contentStylePath)
    );
    await this.#loadScripts();

    Services.obs.notifyObservers(null, ZEN_MODS_UPDATE_TOPIC);
  }

  /**
   * Gives every preference a value before the mod reads it, so `-moz-pref()`
   * queries match the mod's defaults.
   *
   * @param {object[]} applied
   */
  #setDefaults(applied) {
    for (const { name, preferences } of applied) {
      for (const { type, property, defaultValue } of preferences) {
        if (
          !property ||
          defaultValue === undefined ||
          Services.prefs.getPrefType(property) !== Services.prefs.PREF_INVALID
        ) {
          continue;
        }

        if (!["boolean", "string", "number"].includes(typeof defaultValue)) {
          console.warn(
            `[ZenMods]: Invalid default value type (${typeof defaultValue}) for ${property} of ${name}, skipping.`
          );
          continue;
        }

        if (type === "checkbox" || type === "separator") {
          Services.prefs.setBoolPref(
            property,
            defaultValue === true || defaultValue === "true"
          );
        } else {
          Services.prefs.setStringPref(property, String(defaultValue));
        }
      }
    }
  }

  /**
   * Writes `zen-themes-content.css`, the mods' styles for pages, and has
   * every process apply it: each one loads it on its own.
   *
   * @param {string} content
   * @param {boolean} reload - Apply it even if the file is the same
   */
  async #writeContentStylesheet(content, reload) {
    let current = null;

    try {
      current = await IOUtils.readUTF8(this.#contentStyleSheetPath);
    } catch (error) {
      if (!isNotFound(error)) {
        console.warn("[ZenMods]: Could not read the page styles sheet:", error);
      }
    }

    if (current !== content) {
      await IOUtils.writeUTF8(this.#contentStyleSheetPath, content, {
        tmpPath: `${this.#contentStyleSheetPath}.tmp`,
      });
    } else if (!reload) {
      return;
    }

    for (const process of ChromeUtils.getAllDOMProcesses()) {
      try {
        process
          .getActor("ZenModsContent")
          .sendAsyncMessage(CONTENT_RELOAD_MESSAGE);
      } catch (error) {
        console.warn("[ZenMods]: Could not reach a process:", error);
      }
    }
  }

  /**
   * Keeps what tells the user a page went fullscreen out of the mods' reach,
   * for every mod, whatever its CSS says.
   */
  #registerAgentSheet() {
    const sheets = Cc["@mozilla.org/content/style-sheet-service;1"].getService(
      Ci.nsIStyleSheetService
    );
    const uri = Services.io.newURI(AGENT_SHEET_URL);

    if (!sheets.sheetRegistered(uri, sheets.AGENT_SHEET)) {
      sheets.loadAndRegisterSheet(uri, sheets.AGENT_SHEET);
    }
  }

  /**
   * @param {string} content
   * @param {boolean} reload - Apply it even if the file is the same
   */
  async #writeStylesheet(content, reload) {
    let current = null;

    try {
      current = await IOUtils.readUTF8(this.#styleSheetPath);
    } catch (error) {
      if (!isNotFound(error)) {
        console.warn("[ZenMods]: Could not read the mods stylesheet:", error);
      }
    }

    if (current !== content) {
      await IOUtils.writeUTF8(this.#styleSheetPath, content, {
        tmpPath: `${this.#styleSheetPath}.tmp`,
      });
    } else if (!reload) {
      return;
    }

    try {
      lazy.modsBackend.reloadModsStyles();
    } catch (error) {
      console.warn("[ZenMods]: Error reloading the mods styles:", error);
    }
  }
}

