/**
 * Pre-commit guard that keeps Zen's files untouched.
 *
 * Rejects staged changes that
 *   - change a file mode (the noise that used to conflict on every sync), or
 *   - modify/delete/rename a file that exists in upstream/dev, unless it is
 *     listed in peppermint/owned-paths.json (or is a generated compat patch).
 *
 * New files are always fine. Run with --all to check the whole working tree
 * against upstream/dev instead of only the staged changes.
 */

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

function git(...args) {
  return execFileSync("git", args, { cwd: root, encoding: "utf8", maxBuffer: 1 << 28 });
}

function lines(text) {
  return text.split("\n").filter(Boolean);
}

const owned = JSON.parse(fs.readFileSync(path.join(root, "peppermint", "owned-paths.json"), "utf8"));
const compat = fs.existsSync(path.join(root, owned.compatList))
  ? lines(fs.readFileSync(path.join(root, owned.compatList), "utf8"))
  : [];
const allowed = new Set([...owned.edited, ...owned.regenerated, ...owned.deleted, ...compat]);
const allowedPrefixes = [...owned.ours, "peppermint/", "src/peppermint/", "prefs/peppermint/"];
// Generated by Zen's own tooling or by import; nothing to protect.
const ignored = [/^locales\//];

const all = process.argv.includes("--all");
let upstream = null;
try {
  git("rev-parse", "--verify", "upstream/dev");
  upstream = "upstream/dev";
} catch {
  console.warn("check-owned: no upstream/dev ref, skipping the ownership check");
}

// --all compares the working tree with where this branch left upstream, so
// Zen's newer commits do not show up as Peppermint edits.
const mergeBase = upstream ? git("merge-base", upstream, "HEAD").trim() : null;
const base = all && upstream ? mergeBase : upstream;
const diffArgs = all
  ? ["diff", "--name-status", "--no-renames", base]
  : ["diff", "--cached", "--name-status", "--no-renames"];
const problems = [];

function blob(spec) {
  try {
    return execFileSync("git", ["rev-parse", "--verify", "--quiet", spec], {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return null;
  }
}

if (upstream) {
  for (const row of lines(git(...diffArgs))) {
    const [status, file] = row.split("\t");
    if (status === "A") {
      continue;
    }
    if (allowed.has(file) || allowedPrefixes.some(p => file.startsWith(p))) {
      continue;
    }
    if (ignored.some(re => re.test(file))) {
      continue;
    }
    const upstreamBlobs = [blob(`${upstream}:${file}`), blob(`${mergeBase}:${file}`)].filter(Boolean);
    if (!upstreamBlobs.length) {
      continue; // not a Zen file
    }
    if (status !== "D") {
      // Staged (or checked out) content identical to Zen's own copy is fine:
      // that is a revert to upstream or a merge, not a Peppermint edit.
      let current = blob(`:${file}`);
      if (all) {
        try {
          current = git("hash-object", file).trim();
        } catch {
          current = null;
        }
      }
      if (current && upstreamBlobs.includes(current)) {
        continue;
      }
    }
    const hint = file.startsWith("src/")
      ? `edit engine/${file.replace(/^src\//, "")} (or its patch target) and run: npm run pm:record -- <engine path> <feature>`
      : "put the change in peppermint/, src/peppermint/ or prefs/peppermint/, or add the path to peppermint/owned-paths.json";
    problems.push(`${status}\t${file}\n      -> ${hint}`);
  }
}

const summary = !upstream ? "" : git(...(all ? ["diff", "--summary", base] : ["diff", "--cached", "--summary"]));
for (const row of lines(summary)) {
  // Dropping a stray exec bit (755 to 644) is the fix, adding one is the noise.
  if (/mode change 100644 => 100755/.test(row)) {
    problems.push(`mode\t${row.trim()}\n      -> run: chmod 644 <file> (or git update-index --chmod=-x)`);
  }
}

if (problems.length) {
  console.error("check-owned: these changes touch files Zen owns:\n");
  for (const problem of problems) {
    console.error(`  ${problem}`);
  }
  console.error("\nSee AGENTS.md for the layout rules.");
  process.exit(1);
}
console.log("check-owned: ok");
