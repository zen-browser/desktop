const STORE_MOD_ID_RE = /^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$/;
const WHITESPACE_RE = /\s/g;
const NON_NAME_RE = /[^A-Za-z_-]+/g;

// Preferences that only show text; a separator with a property is a toggle.
const LABEL_TYPES = new Set(["text", "separator"]);

// Where a mod's files live and whether its scripts may run is the
// manager's to say, never the store's.
const MANAGER_FIELDS = [
  "source",
  "path",
  "scripts",
  "scriptsApproved",
  "scriptsHash",
  "approvedScriptsHash",
  "stylePath",
  "contentStylePath",
  "preferencesPath",
  "repo",
  "ref",
  "folder",
  "sha",
  "pendingUpdate",
  "enabled",
  "order",
];

