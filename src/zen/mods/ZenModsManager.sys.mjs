/**
 * Builds the id of the element and the prefix that mods use to select their
 * preferences. Do not change to "mod-": published mods depend on "theme-".
 *
 * @param {string} name - The mod's name
 * @returns {string}
 */
function sanitizeModName(name) {
  return `theme-${String(name ?? "")
    .replaceAll(WHITESPACE_RE, "-")
    .replaceAll(NON_NAME_RE, "")}`;
}

/**
 * @param {object} mod - A validated store entry
 * @returns {object} What the registry keeps of it
 */
function storeEntry(mod) {
  const entry = { ...mod };

  for (const key of MANAGER_FIELDS) {
    delete entry[key];
  }

  return entry;
}

/**
 * @param {*} error
 * @returns {boolean} Whether IOUtils failed because the file is not there
 */
function isNotFound(error) {
  return DOMException.isInstance(error) && error.name === "NotFoundError";
}

/**
 * Owns the installed Zen Mods: the registry in `zen-themes.json`, the files
 * in `chrome/zen-themes/<id>/`, the generated `chrome/zen-themes.css` and the
 * updates from the store. One instance serves every window, so a change is
 * built once; windows only apply what needs their DOM (see ZenMods.mjs) and
 * listen to `zen-mods-update`.
 */
class nsZenModsManager {
  /** @type {Promise<void>|null} */
  #ready = null;

  /** @type {Record<string, object>} */
  #mods = {};

  /**
   * The mods that apply right now, with their preferences.
   *
   * @type {{id: string, name: string, sanitizedName: string, preferences: object[]}[]}
   */
  #appliedMods = [];

  /** Serializes registry writes and stylesheet rebuilds. */
  #queue = Promise.resolve();

  /** @type {Promise<object[]|null>|null} */
  #updateCheck = null;

  #autoUpdateScheduled = false;

  /**
   * Why a mod doesn't apply as it should, until it's fixed. Kept in memory:
   * the next session finds out again.
   *
   * @type {Map<string, {type: "missing-files"|"update-failed"|"script-failed", message?: string}>}
   */
  #errors = new Map();

  /** Runs the mods' scripts in windows and documents. */
  #scripts = new ZenModsScripts({
    errors: this.#errors,
    getMod: modId => this.#mods[modId],
    getModFolder: modId => this.getModFolder(modId),
    notifyChanged: () =>
      Services.obs.notifyObservers(null, ZEN_MODS_UPDATE_TOPIC),
  });

  /** @type {Set<object>} Who asked to reload local mods when they change */
  #localWatchers = new Set();

  #isPollingLocalMods = false;

  /** @returns {string} The folder that holds downloaded mods */
  get modsRootPath() {
    return PathUtils.join(PathUtils.profileDir, "chrome", "zen-themes");
  }

  /** @returns {string} The file that lists the installed mods */
  get modsDataFile() {
    return PathUtils.join(PathUtils.profileDir, "zen-themes.json");
  }

  /** @returns {string} The stylesheet built for Zen's windows */
  get #styleSheetPath() {
    return PathUtils.join(PathUtils.profileDir, "chrome", "zen-themes.css");
  }

  /** @returns {string} The stylesheet built for web pages */
  get #contentStyleSheetPath() {
    return PathUtils.join(
      PathUtils.profileDir,
      "chrome",
      "zen-themes-content.css"
    );
  }

  /** Whether mods may apply at all in this session. */
  get modsEnabled() {
    return (
      !Services.prefs.getBoolPref(DISABLE_ALL_PREF, false) &&
      !Services.appinfo.inSafeMode
    );
  }

  /**
   * Whether mod scripts may run. They have every power the browser has, so
   * they stay off until the user turns them on in about:config.
   */
  get scriptsEnabled() {
    return Services.prefs.getBoolPref(SCRIPTS_PREF, false) && this.modsEnabled;
  }

  /** @returns {object[]} The mods that apply right now */
  get appliedMods() {
    return this.#appliedMods;
  }

  /**
   * @param {string} modId
   * @returns {string} The folder that holds the mod's files: its own folder
   * for a local mod, one in the profile for a store mod
   */
  getModFolder(modId) {
    const mod = this.#mods[modId];

    if (mod?.source === "local") {
      return mod.path;
    }

    return PathUtils.join(this.modsRootPath, modId);
  }

  /**
   * @param {object} mod - An entry of the registry
   * @returns {string|null} The mod's style file, if it has one. Store mods
   * always keep it in `chrome.css`.
   */
  #styleFile(mod) {
    const relative = mod.stylePath === undefined ? "chrome.css" : mod.stylePath;

    return (
      relative &&
      PathUtils.join(this.getModFolder(mod.id), ...pathParts(relative))
    );
  }

  /**
   * @param {string} modId
   * @returns {"none"|"needs-approval"|"off"|"running"|"needs-restart"} What
   * the mod's scripts are doing
   */
  getScriptsState(modId) {
    const mod = this.#mods[modId];

    if (this.#scripts.needsRestart(modId)) {
      return "needs-restart";
    }

    if (!declaredScripts(mod).length) {
      return "none";
    }

    if (!this.#areScriptsApproved(mod)) {
      return "needs-approval";
    }

    return this.#scripts.isRunning(modId) ? "running" : "off";
  }

  /**
   * @param {object} mod - An entry of the registry
   * @returns {boolean} Whether the user allowed the mod's scripts: any
   * version of a local mod's, but only the version they saw of a GitHub
   * mod's
   */
  #areScriptsApproved(mod) {
    if (mod.source === "github") {
      return (
        Boolean(mod.approvedScriptsHash) &&
        mod.approvedScriptsHash === mod.scriptsHash
      );
    }

    return Boolean(mod.scriptsApproved);
  }

  /**
   * Loads the registry and builds the stylesheet once per session. Every
   * public method waits for it, so callers don't need to.
   *
   * @returns {Promise<void>}
   */
  init() {
    this.#ready ??= this.#load();

    return this.#ready;
  }

  /**
   * Reads the installed mods and applies them: what `init` waits for.
   */
  async #load() {
    this.#mods = await this.#readRegistry();

    for (const pref of [DISABLE_ALL_PREF, SCRIPTS_PREF]) {
      Services.prefs.addObserver(pref, () => {
        this.#enqueue(() => this.#rebuild());
      });
    }

    this.#registerAgentSheet();

    // The sheet was loaded from disk at startup; only an outdated file needs
    // applying again.
    await this.#enqueue(() => this.#rebuild({ reload: false }));

    // Mods restored without their files, from a backup say, download them
    // again now rather than at the next scheduled update.
    const hasMissingFiles = Object.values(this.#mods).some(
      mod =>
        mod.source !== "local" &&
        this.#errors.get(mod.id)?.type === "missing-files"
    );

    if (hasMissingFiles) {
      ChromeUtils.idleDispatch(() => this.checkForUpdates(), { timeout: 1000 });
    }
  }

  /** @returns {Promise<Record<string, object>>} A copy of the installed mods */
  async getMods() {
    await this.init();

    return structuredClone(this.#mods);
  }

  /** @returns {Promise<object[]>} Copies of the installed mods, in load order */
  async getOrderedMods() {
    await this.init();

    return structuredClone(this.#orderedMods());
  }

  /**
   * @param {string} modId
   * @returns {Promise<boolean>}
   */
  async isModInstalled(modId) {
    await this.init();

    return Object.hasOwn(this.#mods, modId);
  }

  /**
   * @param {string} modId
   * @returns {{type: string, message?: string}|null} Why the mod doesn't apply
   * as it should
   */
  getModError(modId) {
    return this.#errors.get(modId) ?? null;
  }

  /**
   * Mods load in the order the user gave them, and the ones without one after
   * them, in the order they were installed. A later mod wins over an earlier
   * one when both style the same thing.
   *
   * @returns {object[]}
   */
  #orderedMods() {
    return Object.values(this.#mods)
      .map((mod, index) => ({ mod, index }))
      .sort(
        (first, second) =>
          (first.mod.order ?? Infinity) - (second.mod.order ?? Infinity) ||
          first.index - second.index
      )
      .map(({ mod }) => mod);
  }

  /**
   * @param {string[]} modIds - The installed mods, in the order to load them
   * @returns {Promise<void>}
   */
  async setModsOrder(modIds) {
    await this.init();

    await this.#mutate(mods => {
      for (const [index, modId] of modIds.entries()) {
        if (mods[modId]) {
          mods[modId].order = index;
        }
      }
    });
  }

  /**
   * Downloads a store mod again, keeping whether it's enabled and where it
   * loads. Fixes a mod whose files went missing or broke.
   *
   * @param {string} modId
   * @returns {Promise<void>}
   */
  async reinstallMod(modId) {
    await this.init();

    const mod = this.#mods[modId];

    if (mod?.source === "github") {
      const installed = await readGitHubCommit(gitHubSourceOf(mod), mod.sha);

      await this.installGitHubMod(installed);
      return;
    }

    const storeMod = await this.fetchStoreMod(modId);

    await this.installMod(storeMod);
  }

  /**
   * Finds the mod a GitHub repository, or a folder in it, holds at the
   * commit its branch points to now. Nothing is installed.
   *
   * @param {string} input - See parseGitHubSource
   * @returns {Promise<object>} What installGitHubMod takes
   */
  async fetchGitHubMod(input) {
    const source = parseGitHubSource(input);
    const sha = await resolveGitHubCommit(source);

    return readGitHubCommit(source, sha);
  }

  /**
   * Installs a mod `fetchGitHubMod` found, or updates the one installed from
   * the same place. Its files are a copy of that commit's.
   *
   * @param {object} found - What `fetchGitHubMod` returned
   * @param {object} [options]
   * @param {boolean} [options.scriptsApproved] - The user agreed to run the
   * mod's scripts as they are in that commit
   * @returns {Promise<string>} The mod's id
   */
  async installGitHubMod(found, { scriptsApproved = false } = {}) {
    await this.init();

    const existing = Object.values(this.#mods).find(
      mod =>
        mod.source === "github" &&
        mod.repo === found.repo &&
        (mod.folder ?? "") === found.folder
    );
    const modId =
      existing?.id ??
      `${GITHUB_ID_PREFIX}${Services.uuid.generateUUID().toString().slice(1, -1)}`;
    const staged = await stageGitHub(this.modsRootPath, modId, found);

    staged.mod.approvedScriptsHash = scriptsApproved
      ? staged.mod.scriptsHash
      : (existing?.approvedScriptsHash ?? null);

    await this.#commit([staged]);

    return modId;
  }

  /**
   * Installs the update of a GitHub mod that waits because its scripts
   * changed, now that the user allowed them.
   *
   * @param {string} modId
   * @returns {Promise<void>}
   */
  async approveUpdate(modId) {
    await this.init();

    const mod = this.#mods[modId];

    if (mod?.source !== "github" || !mod.pendingUpdate) {
      throw new Error(`[ZenMods]: ${modId} has no update waiting.`);
    }

    const update = await readGitHubCommit(
      gitHubSourceOf(mod),
      mod.pendingUpdate.sha
    );

    await this.installGitHubMod(update, { scriptsApproved: true });
  }

  /**
   * Reads and checks the `theme.json` of a mod in a folder of the user's.
   * Nothing is installed.
   *
   * @param {string} path - The mod's folder
   * @returns {Promise<object>} What the mod declares
   */
  async readLocalMod(path) {
    const manifest = parseManifest(
      await IOUtils.readJSON(PathUtils.join(path, "theme.json"))
    );
    const exists = relative =>
      IOUtils.exists(PathUtils.join(path, ...pathParts(relative)));

    for (const key of ["name", "version"]) {
      if (!manifest[key]) {
        throw new Error(`[ZenMods]: theme.json has no valid "${key}".`);
      }
    }

    for (const { path: script } of manifest.scripts) {
      if (!(await exists(script))) {
        throw new Error(`[ZenMods]: Script ${script} is missing.`);
      }
    }

    manifest.stylePath = await findStyle(manifest.stylePath, exists);

    if (manifest.contentStylePath) {
      const hasContentStyle = await exists(manifest.contentStylePath);

      if (!hasContentStyle) {
        console.warn(
          `[ZenMods]: ${manifest.contentStylePath} is missing, skipping the mod's page styles.`
        );
        manifest.contentStylePath = null;
      }
    }

    if (
      !manifest.stylePath &&
      !manifest.contentStylePath &&
      !manifest.scripts.length
    ) {
      throw new Error("[ZenMods]: The mod has neither styles nor scripts.");
    }

    manifest.preferences = await exists(manifest.preferencesPath);

    return manifest;
  }

  /**
   * Adds a mod that lives in a folder of the user's. The folder isn't copied:
   * editing it and reloading the mod is how mods are made. Installing the
   * same folder again refreshes it.
   *
   * @param {string} path - The mod's folder
   * @param {object} [options]
   * @param {boolean} [options.scriptsApproved] - The user agreed to run the
   * mod's scripts
   * @returns {Promise<string>} The mod's id
   */
  async installLocalMod(path, { scriptsApproved = false } = {}) {
    await this.init();

    const manifest = await this.readLocalMod(path);
    const existing = Object.values(this.#mods).find(
      mod => mod.source === "local" && mod.path === path
    );
    const modId =
      existing?.id ??
      `${LOCAL_ID_PREFIX}${Services.uuid.generateUUID().toString().slice(1, -1)}`;

    const mirror = PathUtils.join(this.modsRootPath, modId);

    // The copy is in place before the sheets import it, and goes only once
    // they stop.
    if (manifest.contentStylePath) {
      await this.#mirrorLocalMod(mirror, path);
    }

    await this.#mutate(
      mods => {
        mods[modId] = {
          ...manifest,
          id: modId,
          source: "local",
          path,
          enabled: existing?.enabled ?? true,
          order: existing?.order,
          scriptsApproved:
            scriptsApproved || Boolean(existing?.scriptsApproved),
        };
        this.#errors.delete(modId);
      },
      async () => {
        if (!manifest.contentStylePath) {
          await IOUtils.remove(mirror, { recursive: true, ignoreAbsent: true });
        }
      }
    );

    return modId;
  }

  /**
   * Content processes may only read the profile's chrome folder, so a local
   * mod with styles for pages gets a copy there. Its styles for Zen and its
   * scripts keep coming from the user's folder.
   *
   * @param {string} mirror - Where the copy goes
   * @param {string} path - The mod's folder
   */
  async #mirrorLocalMod(mirror, path) {
    await IOUtils.makeDirectory(this.modsRootPath, { ignoreExisting: true });

    const staging = await IOUtils.createUniqueDirectory(
      this.modsRootPath,
      `.${PathUtils.filename(mirror)}.staging`
    );

    try {
      for (const { path: file } of await listModFiles(
        path,
        null,
        MAX_LOCAL_FILES
      )) {
        const target = PathUtils.join(
          staging,
          ...PathUtils.splitRelative(file.slice(path.length + 1))
        );

        await IOUtils.makeDirectory(PathUtils.parent(target), {
          ignoreExisting: true,
        });
        await IOUtils.copy(file, target);
      }

      await this.#replaceFolder(staging, mirror);
    } catch (error) {
      await IOUtils.remove(staging, { recursive: true, ignoreAbsent: true });

      throw error;
    }
  }

  /**
   * Reads a local mod's folder again: its `theme.json`, styles and scripts.
   *
   * @param {string} modId
   * @returns {Promise<void>}
   */
  async reloadLocalMod(modId) {
    await this.init();

    const mod = this.#mods[modId];

    if (mod?.source !== "local") {
      throw new Error(`[ZenMods]: ${modId} is not a local mod.`);
    }

    await this.installLocalMod(mod.path);
  }

  /**
   * Reloads local mods when their files change, for as long as someone
   * watches. Checking the folders costs a little, so the Library only
   * watches while it shows the mods.
   *
   * @returns {() => void} Stops watching
   */
  watchLocalMods() {
    const watcher = {};

    this.#localWatchers.add(watcher);

    if (!this.#isPollingLocalMods) {
      this.#pollLocalMods();
    }

    return () => this.#localWatchers.delete(watcher);
  }

  /**
   * Reloads a local mod when its files change, for as long as anyone
   * watches them.
   */
  async #pollLocalMods() {
    const signatures = new Map();

    this.#isPollingLocalMods = true;
    await this.init();

    while (this.#localWatchers.size) {
      for (const mod of Object.values(this.#mods)) {
        if (mod.source !== "local" || mod.enabled === false) {
          continue;
        }

        let signature;

        try {
          const files = await listModFiles(mod.path, null, MAX_LOCAL_FILES);

          signature = files
            .map(
              ({ path, info }) => `${path}:${info.lastModified}:${info.size}`
            )
            .join("\n");
        } catch (error) {
          // A folder that's gone, or too big, changes again when it's fixed.
          signature = String(error);
        }

        const previous = signatures.get(mod.id);

        signatures.set(mod.id, signature);

        if (previous === undefined || previous === signature) {
          continue;
        }

        try {
          await this.reloadLocalMod(mod.id);
        } catch (error) {
          console.warn(`[ZenMods]: Could not reload ${mod.name}:`, error);
        }
      }

      await new Promise(resolve => setTimeout(resolve, LOCAL_POLL_MS));
    }

    this.#isPollingLocalMods = false;
  }

  /**
   * Lets a mod's scripts run once scripts are allowed: any version of a
   * local mod's, the installed version of a GitHub mod's.
   *
   * @param {string} modId
   * @returns {Promise<void>}
   */
  async approveScripts(modId) {
    await this.init();

    await this.#mutate(mods => {
      const mod = mods[modId];

      switch (mod?.source) {
        case "local": {
          mod.scriptsApproved = true;
          break;
        }

        case "github": {
          mod.approvedScriptsHash = mod.scriptsHash;
          break;
        }

        default: {
          throw new Error(`[ZenMods]: ${modId} can't run scripts.`);
        }
      }
    });
  }

  /**
   * Starts in a window the scripts that should run and stops the ones that
   * shouldn't anymore. Windows call it when they open and on every change.
   *
   * @param {Window} win
   */
  syncScripts(win) {
    this.#scripts.sync(win);
  }

  /**
   * Stops the scripts a closing window started.
   *
   * @param {Window} win
   */
  forgetWindow(win) {
    this.#scripts.forgetWindow(win);
  }

  /**
   * Runs the scripts of every enabled mod whose scripts the user approved,
   * while scripts are allowed. Store mods don't run scripts: the store
   * doesn't review them.
   *
   * @returns {Promise<void>}
   */
  #loadScripts() {
    return this.#scripts.load(
      this.scriptsEnabled
        ? this.#orderedMods().filter(
            mod =>
              mod.enabled !== false &&
              this.#areScriptsApproved(mod) &&
              declaredScripts(mod).length
          )
        : []
    );
  }

  /**
   * Reads the preferences a mod declares, without the ones disabled on this
   * operating system.
   *
   * @param {object} mod - An entry of the registry
   * @returns {Promise<object[]>}
   */
  async getModPreferences(mod) {
    if (!mod?.preferences) {
      return [];
    }

    let preferences;

    try {
      preferences = await IOUtils.readJSON(
        PathUtils.join(
          this.getModFolder(mod.id),
          ...pathParts(mod.preferencesPath ?? "preferences.json")
        )
      );
    } catch (error) {
      if (!isNotFound(error)) {
        console.error(
          `[ZenMods]: Error reading the preferences of ${mod.name}:`,
          error
        );
      }

      return [];
    }

    if (!Array.isArray(preferences)) {
      console.warn(
        `[ZenMods]: The preferences of ${mod.name} are not a list, skipping.`
      );

      return [];
    }

    const os = OS_NAMES[Services.appinfo.OS];
    const valid = [];

    for (const preference of preferences) {
      const hasProperty =
        typeof preference?.property === "string" &&
        Boolean(preference.property);

      if (!hasProperty && !LABEL_TYPES.has(preference?.type)) {
        console.warn(
          `[ZenMods]: A preference of ${mod.name} has no property, skipping.`
        );
        continue;
      }

      if (
        Array.isArray(preference.disabledOn) &&
        preference.disabledOn.includes(os)
      ) {
        continue;
      }

      valid.push(
        hasProperty ? preference : { ...preference, property: undefined }
      );
    }

    return valid;
  }

  /**
   * @returns {Promise<object[]>} What the store publishes, the most recently
   * updated first. Only data: nothing is installed.
   */
  async fetchStoreIndex() {
    const url = `${Services.prefs.getStringPref(STORE_URL_PREF)}themes.json`;
    const bytes = await this.#download(url);
    const index = JSON.parse(new TextDecoder().decode(bytes));

    if (!index || typeof index !== "object") {
      throw new Error("[ZenMods]: The mods store index is invalid.");
    }

    const entries = [];

    for (const [modId, mod] of Object.entries(index)) {
      try {
        this.#validateStoreMod(mod, modId);
        entries.push(mod);
      } catch (error) {
        console.warn(
          `[ZenMods]: Invalid store entry ${modId}, skipping.`,
          error
        );
      }
    }

    return entries.sort((first, second) =>
      String(second.updatedAt ?? "").localeCompare(
        String(first.updatedAt ?? "")
      )
    );
  }

  /**
   * @param {*} url
   * @returns {boolean} Whether the URL is the store's, like the images of
   * its mods: chrome only loads those
   */
  isStoreUrl(url) {
    try {
      assertAllowedUrl(String(url), this.#storeUrls());

      return true;
    } catch {
      return false;
    }
  }

  /**
   * Fetches what the store publishes about a mod. The result is only data:
   * nothing is downloaded or installed yet.
   *
   * @param {string} modId
   * @returns {Promise<object>}
   */
  async fetchStoreMod(modId) {
    if (typeof modId !== "string" || !STORE_MOD_ID_RE.test(modId)) {
      throw new Error(`[ZenMods]: Invalid mod id: ${modId}`);
    }

    const url = `${Services.prefs.getStringPref(STORE_URL_PREF)}themes/${modId}/theme.json`;
    const bytes = await this.#download(url);
    const mod = JSON.parse(new TextDecoder().decode(bytes));

    this.#validateStoreMod(mod, modId);

    return mod;
  }

  /**
   * Installs a mod the store published, or replaces it if it's there. The
   * files are downloaded first and only replace the installed ones once all
   * of them arrived, so a failed download never breaks the installed mod.
   *
   * @param {object} mod - What `fetchStoreMod` returned
   * @returns {Promise<void>}
   */
  async installMod(mod) {
    this.#validateStoreMod(mod, mod?.id);

    await this.init();

    const staging = await this.#stage(mod);

    await this.#commit([{ mod: storeEntry(mod), staging }]);
  }

  /**
   * Removes a mod, its files and the preferences it declared, unless another
   * installed mod declares the same preference.
   *
   * @param {string} modId
   * @returns {Promise<void>}
   */
  async uninstallMod(modId) {
    await this.init();

    const mod = this.#mods[modId];

    if (!mod) {
      return;
    }

    const preferences = await this.getModPreferences(mod);

    const folder = this.getModFolder(modId);

    await this.#mutate(
      mods => {
        delete mods[modId];
        this.#errors.delete(modId);
      },
      // Only once the sheets stop importing them: a process loading the old
      // sheet meanwhile would find them gone. A local mod's folder is the
      // user's; only its copy in the profile goes.
      () =>
        IOUtils.remove(
          mod.source === "local"
            ? PathUtils.join(this.modsRootPath, modId)
            : folder,
          { recursive: true, ignoreAbsent: true }
        )
    );

    const stillUsed = new Set();

    for (const other of Object.values(this.#mods)) {
      for (const { property } of await this.getModPreferences(other)) {
        stillUsed.add(property);
      }
    }

    for (const { property } of preferences) {
      // A preference with a default is the browser's, not the mod's.
      if (
        property &&
        !stillUsed.has(property) &&
        !Services.prefs.prefHasDefaultValue(property)
      ) {
        Services.prefs.clearUserPref(property);
      }
    }
  }

  /**
   * @param {string} modId
   * @param {boolean} enabled
   * @returns {Promise<void>}
   */
  async setModEnabled(modId, enabled) {
    await this.init();

    await this.#mutate(mods => {
      if (!mods[modId]) {
        throw new Error(`[ZenMods]: Mod ${modId} is not installed.`);
      }

      mods[modId].enabled = enabled;
    });
  }

  /**
   * Updates every store mod that has a newer version and every GitHub mod
   * whose branch moved, and reinstalls the ones whose files are missing.
   * Concurrent calls share the same check.
   *
   * @returns {Promise<object[]|null>} The updated mods, or null if the store
   * could not be reached
   */
  checkForUpdates() {
    this.#updateCheck ??= this.#runUpdateCheck().finally(() => {
      this.#updateCheck = null;
    });

    return this.#updateCheck;
  }

  /**
   * Checks for updates once per session, when the user allows it and enough
   * days passed. Every window calls this; only the first call counts.
   */
  scheduleAutoUpdate() {
    if (this.#autoUpdateScheduled) {
      return;
    }

    this.#autoUpdateScheduled = true;

    if (
      Services.prefs.getStringPref(MILESTONE_PREF, "") !==
      Services.appinfo.version
    ) {
      Services.prefs.setStringPref(MILESTONE_PREF, Services.appinfo.version);
      Services.prefs.clearUserPref(LAST_UPDATE_PREF);
    }

    const lastUpdate = Services.prefs.getIntPref(LAST_UPDATE_PREF, -1);
    const daysSinceUpdate =
      (Math.floor(Date.now() / 1000) - lastUpdate) / SECONDS_PER_DAY;
    const isDue =
      Services.prefs.getBoolPref(AUTO_UPDATE_PREF, true) &&
      daysSinceUpdate >= Services.prefs.getIntPref(AUTO_UPDATE_DAYS_PREF);

    if (!isDue && lastUpdate >= 0) {
      return;
    }

    ChromeUtils.idleDispatch(() => this.checkForUpdates(), { timeout: 1000 });
  }

  /**
   * @returns {Promise<object[]|null>} The updated mods, or null if the
   * store could not be reached
   */
  async #runUpdateCheck() {
    await this.init();

    const staged = [];
    const pending = [];
    const storeReached = await this.#stageStoreUpdates(staged);

    for (const mod of Object.values(this.#mods)) {
      if (mod.source !== "github") {
        continue;
      }

      try {
        await this.#stageGitHubUpdate(mod, staged, pending);
      } catch (error) {
        console.error(
          `[ZenMods]: Could not update ${mod.name} (${mod.id}), keeping the installed version:`,
          error
        );

        this.#errors.set(mod.id, {
          type: "update-failed",
          message: String(error?.message ?? error),
        });
      }
    }

    if (pending.length) {
      await this.#mutate(mods => {
        for (const { modId, update } of pending) {
          if (mods[modId]) {
            mods[modId].pendingUpdate = update;
          }
        }
      });
    }

    if (staged.length) {
      await this.#commit(staged);
    } else if (!pending.length) {
      // Nothing was rebuilt, but the failed updates are news.
      Services.obs.notifyObservers(null, ZEN_MODS_UPDATE_TOPIC);
    }

    if (!storeReached) {
      return null;
    }

    Services.prefs.setIntPref(LAST_UPDATE_PREF, Math.floor(Date.now() / 1000));

    return staged.map(({ mod }) => mod);
  }

  /**
   * Stages the store mods that have a newer version, and the ones whose
   * files are missing.
   *
   * @param {object[]} staged - Where staged mods go
   * @returns {Promise<boolean>} Whether the store could be reached, if any
   * mod comes from it
   */
  async #stageStoreUpdates(staged) {
    const storeMods = Object.values(this.#mods).filter(mod => !mod.source);

    if (!storeMods.length) {
      return true;
    }

    let index;

    try {
      const url = `${Services.prefs.getStringPref(STORE_URL_PREF)}themes.json`;

      const bytes = await this.#download(url);

      index = JSON.parse(new TextDecoder().decode(bytes));
    } catch (error) {
      console.error("[ZenMods]: Could not fetch the mods store:", error);

      return false;
    }

    if (!index || typeof index !== "object") {
      console.error("[ZenMods]: The mods store index is invalid.");

      return false;
    }

    for (const mod of storeMods) {
      const latest = index[mod.id];

      if (!latest) {
        continue;
      }

      try {
        this.#validateStoreMod(latest, mod.id);

        const isNewer =
          Services.vc.compare(latest.version, mod.version ?? "0.0.0") > 0;
        const hasFiles = await IOUtils.exists(this.#styleFile(mod));

        if (!isNewer && hasFiles) {
          continue;
        }

        console.warn(
          `[ZenMods]: Updating ${mod.name} (${mod.id}) from ${mod.version} to ${latest.version}.`
        );

        staged.push({
          mod: storeEntry(latest),
          staging: await this.#stage(latest),
        });
      } catch (error) {
        console.error(
          `[ZenMods]: Could not update ${mod.name} (${mod.id}), keeping the installed version:`,
          error
        );

        this.#errors.set(mod.id, {
          type: "update-failed",
          message: String(error?.message ?? error),
        });
      }
    }

    return true;
  }

  /**
   * Stages a GitHub mod whose branch moved, or whose files are missing. An
   * update that changes scripts the user allowed waits until they allow it.
   *
   * @param {object} mod - An entry of the registry
   * @param {object[]} staged - Where staged mods go
   * @param {object[]} pending - Where updates that wait go
   */
  async #stageGitHubUpdate(mod, staged, pending) {
    const source = gitHubSourceOf(mod);
    const sha = await resolveGitHubCommit(source);
    const stylePath = this.#styleFile(mod);
    const hasFiles = !stylePath || (await IOUtils.exists(stylePath));

    if ((sha === mod.sha && hasFiles) || sha === mod.pendingUpdate?.sha) {
      return;
    }

    const found = await readGitHubCommit(source, sha);
    const update = await stageGitHub(this.modsRootPath, mod.id, found);
    const { scriptsHash } = update.mod;

    if (
      mod.approvedScriptsHash &&
      scriptsHash &&
      scriptsHash !== mod.approvedScriptsHash
    ) {
      console.warn(
        `[ZenMods]: The update of ${mod.name} (${mod.id}) changes its scripts, waiting for the user to allow them.`
      );

      await IOUtils.remove(update.staging, {
        recursive: true,
        ignoreAbsent: true,
      });
      pending.push({
        modId: mod.id,
        update: { sha, version: update.mod.version },
      });

      return;
    }

    update.mod.approvedScriptsHash = mod.approvedScriptsHash ?? null;
    staged.push(update);
  }

  /**
   * Checks the parts of a store entry that end up in paths and URLs.
   *
   * @param {object} mod
   * @param {string} expectedId - The id the mod was requested with
   */
  #validateStoreMod(mod, expectedId) {
    if (!mod || typeof mod !== "object") {
      throw new Error("[ZenMods]: The mod data is not an object.");
    }

    if (mod.id !== expectedId || !STORE_MOD_ID_RE.test(mod.id)) {
      throw new Error(`[ZenMods]: Unexpected mod id: ${mod.id}`);
    }

    for (const key of ["name", "style", "version"]) {
      if (typeof mod[key] !== "string" || !mod[key]) {
        throw new Error(`[ZenMods]: Mod ${mod.id} has no valid "${key}".`);
      }
    }
  }

  /**
   * Downloads a store mod's files into a fresh folder next to the installed
   * ones.
   *
   * @param {object} mod - A validated store entry
   * @returns {Promise<string>} The folder with the downloaded files
   */
  async #stage(mod) {
    await IOUtils.makeDirectory(this.modsRootPath, { ignoreExisting: true });

    const staging = await IOUtils.createUniqueDirectory(
      this.modsRootPath,
      `.${mod.id}.staging`
    );
    const files = [
      { name: "chrome.css", url: mod.style, required: true },
      { name: "preferences.json", url: mod.preferences, required: true },
      { name: "readme.md", url: mod.readme, required: false },
    ];

    try {
      for (const { name, url, required } of files) {
        if (!url) {
          continue;
        }

        try {
          const bytes = await this.#download(url);

          await IOUtils.write(PathUtils.join(staging, name), bytes);
        } catch (error) {
          if (required) {
            throw error;
          }

          console.warn(
            `[ZenMods]: Could not download ${name} of ${mod.name}, skipping.`,
            error
          );
        }
      }

      await assertLocalStyles(staging, mod.name, ["chrome.css"]);
    } catch (error) {
      await IOUtils.remove(staging, { recursive: true, ignoreAbsent: true });

      throw error;
    }

    return staging;
  }

  /**
   * Puts staged mods in place and records them, keeping whether each one was
   * enabled and where it loads.
   *
   * @param {{mod: object, staging: string}[]} staged
   */
  async #commit(staged) {
    await this.#mutate(async mods => {
      for (const { mod, staging } of staged) {
        const previous = mods[mod.id];

        await this.#replaceFolder(staging, this.getModFolder(mod.id));

        mods[mod.id] = {
          ...mod,
          enabled: previous?.enabled ?? true,
          order: previous?.order,
        };
        this.#errors.delete(mod.id);
      }
    });
  }

  /**
   * Moves a staged folder to where the mod's folder is, and puts the old
   * one back if that fails.
   *
   * @param {string} staging
   * @param {string} folder
   */
  async #replaceFolder(staging, folder) {
    const previous = `${staging}.previous`;
    const hadFolder = await IOUtils.exists(folder);

    if (hadFolder) {
      await IOUtils.move(folder, previous);
    }

    try {
      await IOUtils.move(staging, folder);
    } catch (error) {
      if (hadFolder) {
        await IOUtils.move(previous, folder);
      }

      throw error;
    }

    await IOUtils.remove(previous, { recursive: true, ignoreAbsent: true });
  }

  /** @returns {string[]} Where store files may come from */
  #storeUrls() {
    return [
      Services.prefs.getStringPref(STORE_URL_PREF),
      Services.prefs.getStringPref(STORE_ASSETS_URL_PREF),
    ];
  }

  /**
   * @param {string} url - A file from the store
   * @returns {Promise<Uint8Array>}
   */
  #download(url) {
    return download(url, { allowed: this.#storeUrls() });
  }

  /**
   * A data file that isn't a list of mods is replaced by an empty one, and
   * the user is told.
   *
   * @returns {Promise<Record<string, object>>} The installed mods
   */
  async #readRegistry() {
    let data;

    try {
      data = await IOUtils.readJSON(this.modsDataFile);
    } catch (error) {
      if (isNotFound(error)) {
        await this.#writeRegistry({});

        return {};
      }

      console.warn("[ZenMods]: Could not read the mods data file:", error);
    }

    if (!data || typeof data !== "object" || Array.isArray(data)) {
      await this.#writeRegistry({});

      Services.wm
        .getMostRecentWindow("navigator:browser")
        ?.gZenUIManager?.showToast("zen-themes-corrupted", { timeout: 8000 });

      return {};
    }

    const mods = {};

    for (const [id, mod] of Object.entries(data)) {
      if (!mod || typeof mod !== "object") {
        console.warn(`[ZenMods]: Invalid entry for mod ${id}, skipping.`);
        continue;
      }

      mods[id] = { ...mod, id };
    }

    return mods;
  }

  /**
   * @param {Record<string, object>} mods - Every installed mod, by id
   */
  async #writeRegistry(mods) {
    await IOUtils.writeJSON(this.modsDataFile, mods, {
      tmpPath: `${this.modsDataFile}.tmp`,
    });
  }

  /**
   * Runs a task after every write and rebuild queued before it.
   *
   * @param {() => Promise<*>} task
   * @returns {Promise<*>}
   */
  #enqueue(task) {
    const run = this.#queue.then(task);

    this.#queue = run.catch(() => {});

    return run;
  }

  /**
   * Changes the registry, saves it and rebuilds the stylesheet, one change at
   * a time.
   *
   * @param {(mods: Record<string, object>) => *} change
   * @param {() => Promise<void>} [afterRebuild] - Runs once the stylesheets
   * no longer point at what it removes, before the next change
   * @returns {Promise<*>}
   */
  #mutate(change, afterRebuild) {
    return this.#enqueue(async () => {
      const result = await change(this.#mods);

      await this.#writeRegistry(this.#mods);
      await this.#rebuild();
      await afterRebuild?.();

      return result;
    });
  }

  /**
   * Writes `zen-themes.css` as one `@import` per enabled mod, so each mod is
   * its own sheet: a mod with broken CSS can't swallow the ones after it,
   * and errors point at the mod's own file.
   *
   * @param {object} [options]
   * @param {boolean} [options.reload] - Apply the sheet even if the file
   * didn't change, because a mod's own file may have.
   */
  async #rebuild({ reload = true } = {}) {
    const mods = this.modsEnabled
      ? this.#orderedMods().filter(mod => mod.enabled !== false)
      : [];
    const applied = [];

    let content = STYLESHEET_HEADER;
    let pageContent = STYLESHEET_HEADER;

    for (const mod of mods) {
      const stylePath = this.#styleFile(mod);
      const hasStyles = Boolean(stylePath) && (await IOUtils.exists(stylePath));

      // Page styles of every mod come from the profile, local mods' too,
      // through their copy there.
      if (mod.contentStylePath) {
        pageContent += `@import url("zen-themes/${encodeURIComponent(mod.id)}/${encodePath(mod.contentStylePath)}");\n`;
      }

      if (!hasStyles && !mod.contentStylePath && !declaredScripts(mod).length) {
        console.warn(
          `[ZenMods]: ${mod.name} (${mod.id}) has no styles, skipping.`
        );

        this.#errors.set(mod.id, { type: "missing-files" });
        continue;
      }

      if (this.#errors.get(mod.id)?.type === "missing-files") {
        this.#errors.delete(mod.id);
      }

      if (hasStyles) {
        // Store mods live next to the sheet; local ones wherever the user
        // keeps them.
        const url =
          mod.source === "local"
            ? PathUtils.toFileURI(stylePath)
            : `zen-themes/${encodeURIComponent(mod.id)}/${encodePath(mod.stylePath ?? "chrome.css")}`;

        content += `@import url("${url}");\n`;
      }

      applied.push({
        id: mod.id,
        name: mod.name,
        sanitizedName: sanitizeModName(mod.name),
        preferences: await this.getModPreferences(mod),
      });
    }

    this.#setDefaults(applied);
    this.#appliedMods = applied;

    await this.#writeStylesheet(content, reload);
    await this.#writeContentStylesheet(
      pageContent,
      reload && mods.some(mod => mod.contentStylePath)
    );
    await this.#loadScripts();

    Services.obs.notifyObservers(null, ZEN_MODS_UPDATE_TOPIC);
  }

  /**
   * Gives every preference a value before the mod reads it, so `-moz-pref()`
   * queries match the mod's defaults.
   *
   * @param {object[]} applied
   */
  #setDefaults(applied) {
    for (const { name, preferences } of applied) {
      for (const { type, property, defaultValue } of preferences) {
        if (
          !property ||
          defaultValue === undefined ||
          Services.prefs.getPrefType(property) !== Services.prefs.PREF_INVALID
        ) {
          continue;
        }

        if (!["boolean", "string", "number"].includes(typeof defaultValue)) {
          console.warn(
            `[ZenMods]: Invalid default value type (${typeof defaultValue}) for ${property} of ${name}, skipping.`
          );
          continue;
        }

        if (type === "checkbox" || type === "separator") {
          Services.prefs.setBoolPref(
            property,
            defaultValue === true || defaultValue === "true"
          );
        } else {
          Services.prefs.setStringPref(property, String(defaultValue));
        }
      }
    }
  }

  /**
   * Writes `zen-themes-content.css`, the mods' styles for pages, and has
   * every process apply it: each one loads it on its own.
   *
   * @param {string} content
   * @param {boolean} reload - Apply it even if the file is the same
   */
  async #writeContentStylesheet(content, reload) {
    let current = null;

    try {
      current = await IOUtils.readUTF8(this.#contentStyleSheetPath);
    } catch (error) {
      if (!isNotFound(error)) {
        console.warn("[ZenMods]: Could not read the page styles sheet:", error);
      }
    }

    if (current !== content) {
      await IOUtils.writeUTF8(this.#contentStyleSheetPath, content, {
        tmpPath: `${this.#contentStyleSheetPath}.tmp`,
      });
    } else if (!reload) {
      return;
    }

    for (const process of ChromeUtils.getAllDOMProcesses()) {
      try {
        process
          .getActor("ZenModsContent")
          .sendAsyncMessage(CONTENT_RELOAD_MESSAGE);
      } catch (error) {
        console.warn("[ZenMods]: Could not reach a process:", error);
      }
    }
  }

  /**
   * Keeps what tells the user a page went fullscreen out of the mods' reach,
   * for every mod, whatever its CSS says.
   */
  #registerAgentSheet() {
    const sheets = Cc["@mozilla.org/content/style-sheet-service;1"].getService(
      Ci.nsIStyleSheetService
    );
    const uri = Services.io.newURI(AGENT_SHEET_URL);

    if (!sheets.sheetRegistered(uri, sheets.AGENT_SHEET)) {
      sheets.loadAndRegisterSheet(uri, sheets.AGENT_SHEET);
    }
  }

  /**
   * @param {string} content
   * @param {boolean} reload - Apply it even if the file is the same
   */
  async #writeStylesheet(content, reload) {
    let current = null;

    try {
      current = await IOUtils.readUTF8(this.#styleSheetPath);
    } catch (error) {
      if (!isNotFound(error)) {
        console.warn("[ZenMods]: Could not read the mods stylesheet:", error);
      }
    }

    if (current !== content) {
      await IOUtils.writeUTF8(this.#styleSheetPath, content, {
        tmpPath: `${this.#styleSheetPath}.tmp`,
      });
    } else if (!reload) {
      return;
    }

    try {
      lazy.modsBackend.reloadModsStyles();
    } catch (error) {
      console.warn("[ZenMods]: Error reloading the mods styles:", error);
    }
  }
}

